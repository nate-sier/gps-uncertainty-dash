# Exact CMJ flag reproduction settings.
CMJ_MIN_PRIOR_SESSIONS = 6
CMJ_MONITOR_Z = -1.5
CMJ_REVIEW_Z = -2.0
CMJ_P1_MIN_DECLINE_PCT = 3.0
CMJ_BW_MIN_LOSS_LB = 4.0
CMJ_STATUS_SCORE = {"": 0, "MONITOR": 1, "REVIEW": 2}


def _cmj_worse(*levels):
    valid = [x for x in levels if x in {"MONITOR", "REVIEW"}]
    if not valid:
        return ""
    return max(valid, key=lambda x: CMJ_STATUS_SCORE[x])


def _cmj_expanding_z(values, idx, floor):
    prior = pd.to_numeric(pd.Series(values[:idx]), errors="coerce").dropna()
    today = pd.to_numeric(pd.Series([values[idx]]), errors="coerce").iloc[0]
    if len(prior) < CMJ_MIN_PRIOR_SESSIONS or pd.isna(today):
        return np.nan
    mean = float(prior.mean())
    sd = max(float(prior.std(ddof=1)), float(floor))
    if not np.isfinite(sd) or sd == 0:
        return np.nan
    return (float(today) - mean) / sd


def _cmj_z_level(z, direction):
    if pd.isna(z):
        return ""
    z_eff = float(z) * float(direction)
    if z_eff <= CMJ_REVIEW_Z:
        return "REVIEW"
    if z_eff <= CMJ_MONITOR_Z:
        return "MONITOR"
    return ""


def _cmj_consecutive_decline(values, idx, direction):
    """Count consecutive worsening steps ending at idx."""
    streak = 0
    j = idx
    while j > 0:
        cur = values[j]
        prev = values[j - 1]
        if pd.isna(cur) or pd.isna(prev):
            break
        worsened = (cur < prev) if direction == 1 else (cur > prev)
        if not worsened:
            break
        streak += 1
        j -= 1
    return streak


def _cmj_trend_level(streak, z):
    if streak < 3:
        return ""
    if streak >= 4:
        return "REVIEW"
    # Reproduce the supplied rule exactly: a 3-session trend is suppressed
    # when the raw z-score remains above zero.
    if not pd.isna(z) and float(z) > 0:
        return ""
    return "MONITOR"


def add_cmj_reproduction_flags(jump_sessions: pd.DataFrame) -> pd.DataFrame:
    """Apply the supplied CMJ flag specification to one-row-per-session data.

    Flags are calculated chronologically within athlete and use only prior
    sessions. Eccentric duration is converted from milliseconds to seconds so
    its 0.03 SD floor matches the specification. Bodyweight is evaluated in lb.
    """
    out = jump_sessions.sort_values(["player_key", "date"]).copy()
    result_parts = []
    for _, g in out.groupby("player_key", sort=False):
        g = g.sort_values("date").copy().reset_index(drop=True)
        # Restrict the baseline to the configured current season.
        season_start = pd.Timestamp(START_DATE) if START_DATE else pd.Timestamp(
            year=int(g["date"].dt.year.max()), month=1, day=1
        )
        season_mask = g["date"].ge(season_start)
        season = g.loc[season_mask].copy().reset_index(drop=True)
        n = len(season)
        pre = g.loc[~season_mask].copy()
        if season.empty:
            result_parts.append(g)
            continue

        ci = pd.to_numeric(season.get("jump_ci_ns"), errors="coerce").to_numpy(float)
        mrsi = pd.to_numeric(season.get("jump_mrsi"), errors="coerce").to_numpy(float)
        p1 = pd.to_numeric(season.get("jump_p1_ci_ns"), errors="coerce").to_numpy(float)
        cmd = pd.to_numeric(season.get("jump_countermovement_depth_cm"), errors="coerce").to_numpy(float)
        ecc_ms = pd.to_numeric(season.get("jump_ecc_duration_ms"), errors="coerce")
        ecc = (ecc_ms / 1000.0).to_numpy(float)
        if "jump_bw_lb" in season.columns:
            bw = pd.to_numeric(season["jump_bw_lb"], errors="coerce")
        else:
            bw = pd.Series(np.nan, index=season.index)
        if "jump_bw_kg" in season.columns:
            bw = bw.fillna(pd.to_numeric(season["jump_bw_kg"], errors="coerce") * 2.2046226218)
        bw = bw.to_numpy(float)

        rows = []
        for i in range(n):
            rec = {}
            # CI
            ci_z = _cmj_expanding_z(ci, i, 8.0)
            ci_streak = _cmj_consecutive_decline(ci, i, +1)
            ci_level = _cmj_worse(_cmj_z_level(ci_z, +1), _cmj_trend_level(ci_streak, ci_z))
            ci_flagged = bool(ci_level)
            ci_declining = ci_flagged or ci_streak >= 1

            # mRSI, independent.
            mrsi_z = _cmj_expanding_z(mrsi, i, 0.03)
            mrsi_streak = _cmj_consecutive_decline(mrsi, i, +1)
            mrsi_level = _cmj_worse(_cmj_z_level(mrsi_z, +1), _cmj_trend_level(mrsi_streak, mrsi_z))

            # P1, gated by CI flag and >=3% real decline from prior median.
            p1_z = _cmj_expanding_z(p1, i, 7.0)
            p1_prior = pd.Series(p1[:i]).dropna()
            p1_baseline = float(p1_prior.median()) if len(p1_prior) >= CMJ_MIN_PRIOR_SESSIONS else np.nan
            p1_pct_decline = np.nan
            if np.isfinite(p1_baseline) and p1_baseline != 0 and np.isfinite(p1[i]):
                p1_pct_decline = (p1_baseline - p1[i]) / abs(p1_baseline) * 100.0
            p1_pct_ok = bool(np.isfinite(p1_pct_decline) and p1_pct_decline >= CMJ_P1_MIN_DECLINE_PCT)
            p1_streak = _cmj_consecutive_decline(p1, i, +1)
            if ci_flagged and p1_pct_ok:
                p1_level = _cmj_worse(_cmj_z_level(p1_z, +1), _cmj_trend_level(p1_streak, p1_z))
            else:
                p1_level = ""

            # CMD, evaluated only when CI is flagged.
            cmd_z = np.nan
            cmd_streak = _cmj_consecutive_decline(cmd, i, +1)
            cmd_level = ""
            if ci_flagged:
                cmd_z = _cmj_expanding_z(cmd, i, 2.5)
                cmd_level = _cmj_z_level(cmd_z, +1)
                if ci_declining:
                    cmd_level = _cmj_worse(cmd_level, _cmj_trend_level(cmd_streak, cmd_z))

            # Compound override.
            if ci_flagged and bool(cmd_level):
                ci_level = "REVIEW"
                cmd_level = "REVIEW"
                ci_flagged = True

            # Eccentric duration, evaluated only after CMD flag/override.
            ecc_z = np.nan
            ecc_streak = _cmj_consecutive_decline(ecc, i, -1)
            ecc_level = ""
            if bool(cmd_level):
                ecc_z = _cmj_expanding_z(ecc, i, 0.03)
                ecc_level = _cmj_worse(_cmj_z_level(ecc_z, -1), _cmj_trend_level(ecc_streak, ecc_z))

            # Bodyweight streak only.
            bw_streak = _cmj_consecutive_decline(bw, i, +1)
            bw_total_loss = np.nan
            bw_level = ""
            if bw_streak >= 3 and i - bw_streak >= 0 and np.isfinite(bw[i]):
                start_bw = bw[i - bw_streak]
                if np.isfinite(start_bw):
                    bw_total_loss = start_bw - bw[i]
                    if bw_total_loss >= CMJ_BW_MIN_LOSS_LB:
                        bw_level = "MONITOR"

            overall = _cmj_worse(ci_level, mrsi_level, p1_level, cmd_level, ecc_level, bw_level)
            rec.update({
                "cmj_ci_z": ci_z, "cmj_ci_decline_streak": ci_streak, "cmj_ci_level": ci_level,
                "cmj_ci_flagged": int(bool(ci_level)), "cmj_ci_declining": int(ci_declining),
                "cmj_mrsi_z": mrsi_z, "cmj_mrsi_decline_streak": mrsi_streak, "cmj_mrsi_level": mrsi_level,
                "cmj_mrsi_flagged": int(bool(mrsi_level)),
                "cmj_p1_z": p1_z, "cmj_p1_prior_median": p1_baseline,
                "cmj_p1_pct_decline": p1_pct_decline, "cmj_p1_pct_gate_met": int(p1_pct_ok),
                "cmj_p1_decline_streak": p1_streak, "cmj_p1_level": p1_level,
                "cmj_p1_flagged": int(bool(p1_level)),
                "cmj_cmd_z": cmd_z, "cmj_cmd_decline_streak": cmd_streak, "cmj_cmd_level": cmd_level,
                "cmj_cmd_flagged": int(bool(cmd_level)),
                "cmj_ecc_duration_s": ecc[i] if i < len(ecc) else np.nan,
                "cmj_ecc_z": ecc_z, "cmj_ecc_increase_streak": ecc_streak, "cmj_ecc_level": ecc_level,
                "cmj_ecc_flagged": int(bool(ecc_level)),
                "cmj_bw_lb": bw[i] if i < len(bw) else np.nan,
                "cmj_bw_loss_streak": bw_streak, "cmj_bw_total_loss_lb": bw_total_loss,
                "cmj_bw_level": bw_level, "cmj_bw_flagged": int(bool(bw_level)),
                "cmj_overall_status": overall,
                "cmj_overall_severity_score": CMJ_STATUS_SCORE.get(overall, 0),
                "cmj_any_flag": int(bool(overall)),
                "cmj_review_flag": int(overall == "REVIEW"),
                "cmj_monitor_flag": int(overall == "MONITOR"),
                "cmj_prior_session_count": i,
                "cmj_minimum_baseline_met": int(i >= CMJ_MIN_PRIOR_SESSIONS),
            })
            rows.append(rec)
        flags = pd.DataFrame(rows)
        season = pd.concat([season.reset_index(drop=True), flags], axis=1)
        if not pre.empty:
            # Pre-season rows remain present but are not used by current-season flags.
            for c in flags.columns:
                pre[c] = np.nan
            g2 = pd.concat([pre, season], ignore_index=True).sort_values("date")
        else:
            g2 = season
        result_parts.append(g2)
    return pd.concat(result_parts, ignore_index=True) if result_parts else out
