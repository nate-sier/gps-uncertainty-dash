def _sum_with_na(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce")
    return values.sum(min_count=1)


def build_jump_response_dataset(
    df: pd.DataFrame,
    window_days: int,
    metric_col: str,
) -> pd.DataFrame:
    """Create one row per jump test with preceding workload and plan execution."""
    required = {"player_key", "date", metric_col, "jump_observed"}
    if not required.issubset(df.columns):
        return pd.DataFrame()

    work = df.sort_values(["player_key", "date"]).copy()
    jump_mask = (safe_numeric(work["jump_observed"], default=0) == 1) & work[metric_col].notna()
    jumps = work.loc[jump_mask, [
        "player_key", "player_name", "team", "position_group", "date", metric_col
    ]].copy()
    if jumps.empty:
        return jumps

    jumps = jumps.sort_values(["player_key", "date"])
    jumps["previous_jump_value"] = jumps.groupby("player_key")[metric_col].shift(1)
    jumps["previous_jump_date"] = jumps.groupby("player_key")["date"].shift(1)
    jumps["days_since_previous_jump"] = (
        jumps["date"] - jumps["previous_jump_date"]
    ).dt.days
    jumps["jump_change_absolute"] = jumps[metric_col] - jumps["previous_jump_value"]
    denominator = jumps["previous_jump_value"].abs().replace(0, np.nan)
    jumps["jump_change_pct"] = 100 * jumps["jump_change_absolute"] / denominator

    rows = []
    for row in jumps.itertuples(index=False):
        end = row.date - pd.Timedelta(days=1)
        start = row.date - pd.Timedelta(days=window_days)
        window = work.loc[
            work["player_key"].eq(row.player_key)
            & work["date"].between(start, end)
        ]

        measured_plans = window.loc[window["practice_plan_evaluable_observed"]].copy()
        plan_days = len(measured_plans)
        misses = int((~measured_plans["practice_plan_hit_observed"]).sum()) if plan_days else 0
        hits = int(measured_plans["practice_plan_hit_observed"].sum()) if plan_days else 0
        miss_pct = 100 * safe_rate(misses, plan_days)

        rows.append({
            "player_key": row.player_key,
            "player_name": row.player_name,
            "team": row.team,
            "position_group": row.position_group,
            "jump_date": row.date,
            "jump_value": getattr(row, metric_col),
            "previous_jump_value": row.previous_jump_value,
            "previous_jump_date": row.previous_jump_date,
            "days_since_previous_jump": row.days_since_previous_jump,
            "jump_change_absolute": row.jump_change_absolute,
            "jump_change_pct": row.jump_change_pct,
            "window_days": window_days,
            "window_start": start,
            "window_end": end,
            "window_measured_plan_days": plan_days,
            "window_plan_hits": hits,
            "window_plan_misses": misses,
            "window_plan_miss_pct": miss_pct,
            "window_any_plan_miss": misses > 0,
            "window_below_target_days": int(measured_plans["practice_plan_result"].eq("Below target").sum()),
            "window_above_target_days": int(measured_plans["practice_plan_result"].eq("Above target").sum()),
            "window_mixed_miss_days": int(measured_plans["practice_plan_result"].eq("Mixed miss").sum()),
            "window_all_missed_high_days": int((
                measured_plans["planned_day_type_3level"].eq("High")
                & ~measured_plans["practice_plan_hit_observed"]
            ).sum()),
            "window_all_missed_low_days": int((
                measured_plans["planned_day_type_3level"].eq("Low")
                & ~measured_plans["practice_plan_hit_observed"]
            ).sum()),
            "window_high_below_target_days": int(measured_plans["practice_plan_result_detail"].eq("High below target").sum()),
            "window_high_above_target_days": int(measured_plans["practice_plan_result_detail"].eq("High above target").sum()),
            "window_moderate_below_target_days": int(measured_plans["practice_plan_result_detail"].eq("Moderate below target").sum()),
            "window_moderate_above_target_days": int(measured_plans["practice_plan_result_detail"].eq("Moderate above target").sum()),
            "window_moderate_mixed_miss_days": int(measured_plans["practice_plan_result_detail"].eq("Moderate mixed miss").sum()),
            "window_low_above_target_days": int(measured_plans["practice_plan_result_detail"].eq("Low above target").sum()),
            "window_total_distance_m": _sum_with_na(window.get("on_field_total_distance_m", pd.Series(dtype=float))),
            "window_high_intensity_distance_m": _sum_with_na(window.get("on_field_high_intensity_distance_proxy_m", pd.Series(dtype=float))),
            "window_practice_total_distance_m": _sum_with_na(window.get("gps_total_distance_m", pd.Series(dtype=float))),
            "window_practice_hsr_m": _sum_with_na(window.get("gps_hsr_distance_m", pd.Series(dtype=float))),
            "window_practice_accels": _sum_with_na(window.get("gps_n_accelerations", pd.Series(dtype=float))),
            "window_game_distance_m": _sum_with_na(window.get("game_distance_covered_m", pd.Series(dtype=float))),
            "window_game_max_effort_distance_m": _sum_with_na(window.get("game_max_effort_distance_m", pd.Series(dtype=float))),
            "window_game_max_effort_runs": _sum_with_na(window.get("game_max_effort_runs", pd.Series(dtype=float))),
            "window_practice_observed_days": int(safe_numeric(window.get("gps_observed", pd.Series(0, index=window.index)), default=0).sum()),
            "window_game_days": int(safe_numeric(window.get("game_day", pd.Series(0, index=window.index)), default=0).sum()),
            "window_on_field_observed_days": int(safe_numeric(window.get("on_field_load_observed", pd.Series(0, index=window.index)), default=0).sum()),
        })

    result = pd.DataFrame(rows)
    result["miss_group"] = np.select(
        [result["window_plan_misses"].eq(0), result["window_plan_misses"].eq(1)],
        ["0 misses", "1 miss"],
        default="2+ misses",
    )
    return result



def build_cmj_flag_impact_dataset(df: pd.DataFrame, window_days: int) -> pd.DataFrame:
    """One row per CMJ session with preceding workload/miss exposure and flag outcomes."""
    required = {"player_key", "date", "jump_observed"}
    if not required.issubset(df.columns):
        return pd.DataFrame()

    work = df.sort_values(["player_key", "date"]).copy()
    jump_mask = safe_numeric(work["jump_observed"], default=0).eq(1)
    sessions = work.loc[jump_mask].copy()
    if sessions.empty:
        return pd.DataFrame()

    flag_cols = [
        "cmj_ci_flagged", "cmj_mrsi_flagged", "cmj_p1_flagged",
        "cmj_cmd_flagged", "cmj_ecc_flagged", "cmj_bw_flagged",
    ]
    for col in flag_cols + ["cmj_any_flag", "cmj_review_flag", "cmj_monitor_flag", "cmj_overall_severity_score"]:
        if col not in sessions.columns:
            sessions[col] = 0
        sessions[col] = safe_numeric(sessions[col], default=0)

    sessions["cmj_metric_flag_count"] = sessions[flag_cols].sum(axis=1)
    sessions = sessions.sort_values(["player_key", "date"])
    sessions["previous_cmj_any_flag"] = sessions.groupby("player_key")["cmj_any_flag"].shift(1).fillna(0)
    sessions["previous_cmj_review_flag"] = sessions.groupby("player_key")["cmj_review_flag"].shift(1).fillna(0)
    sessions["previous_cmj_metric_flag_count"] = sessions.groupby("player_key")["cmj_metric_flag_count"].shift(1)
    sessions["cmj_new_flag_onset"] = ((sessions["cmj_any_flag"] == 1) & (sessions["previous_cmj_any_flag"] == 0)).astype(int)
    sessions["cmj_new_review_onset"] = ((sessions["cmj_review_flag"] == 1) & (sessions["previous_cmj_review_flag"] == 0)).astype(int)
    sessions["cmj_flag_count_change"] = sessions["cmj_metric_flag_count"] - sessions["previous_cmj_metric_flag_count"]

    rows = []
    for row in sessions.itertuples(index=False):
        end = row.date - pd.Timedelta(days=1)
        start = row.date - pd.Timedelta(days=window_days)
        window = work.loc[
            work["player_key"].eq(row.player_key)
            & work["date"].between(start, end)
        ].copy()
        measured = window.loc[window.get("practice_plan_evaluable_observed", False)].copy() if "practice_plan_evaluable_observed" in window.columns else window.iloc[0:0].copy()
        plan_days = len(measured)
        misses = int((~measured["practice_plan_hit_observed"].astype(bool)).sum()) if plan_days and "practice_plan_hit_observed" in measured.columns else 0

        def count_detail(label: str) -> int:
            if "practice_plan_result_detail" not in measured.columns:
                return 0
            return int(measured["practice_plan_result_detail"].eq(label).sum())

        rows.append({
            "player_key": row.player_key,
            "player_name": getattr(row, "player_name", row.player_key),
            "team": getattr(row, "team", "Unknown"),
            "position_group": getattr(row, "position_group", "Unknown"),
            "jump_date": row.date,
            "window_days": window_days,
            "window_start": start,
            "window_end": end,
            "window_measured_plan_days": plan_days,
            "window_plan_misses": misses,
            "window_plan_miss_pct": 100 * safe_rate(misses, plan_days),
            "window_any_plan_miss": int(misses > 0),
            "window_high_below_target_days": count_detail("High below target"),
            "window_high_above_target_days": count_detail("High above target"),
            "window_moderate_below_target_days": count_detail("Moderate below target"),
            "window_moderate_above_target_days": count_detail("Moderate above target"),
            "window_moderate_mixed_miss_days": count_detail("Moderate mixed miss"),
            "window_low_above_target_days": count_detail("Low above target"),
            "window_total_distance_m": _sum_with_na(window.get("on_field_total_distance_m", pd.Series(dtype=float))),
            "window_high_intensity_distance_m": _sum_with_na(window.get("on_field_high_intensity_distance_proxy_m", pd.Series(dtype=float))),
            "window_practice_total_distance_m": _sum_with_na(window.get("gps_total_distance_m", pd.Series(dtype=float))),
            "window_practice_hsr_m": _sum_with_na(window.get("gps_hsr_distance_m", pd.Series(dtype=float))),
            "window_practice_accels": _sum_with_na(window.get("gps_n_accelerations", pd.Series(dtype=float))),
            "window_game_distance_m": _sum_with_na(window.get("game_distance_covered_m", pd.Series(dtype=float))),
            "window_game_max_effort_distance_m": _sum_with_na(window.get("game_max_effort_distance_m", pd.Series(dtype=float))),
            "window_game_max_effort_runs": _sum_with_na(window.get("game_max_effort_runs", pd.Series(dtype=float))),
            "cmj_any_flag": int(getattr(row, "cmj_any_flag", 0)),
            "cmj_monitor_flag": int(getattr(row, "cmj_monitor_flag", 0)),
            "cmj_review_flag": int(getattr(row, "cmj_review_flag", 0)),
            "cmj_new_flag_onset": int(getattr(row, "cmj_new_flag_onset", 0)),
            "cmj_new_review_onset": int(getattr(row, "cmj_new_review_onset", 0)),
            "cmj_metric_flag_count": float(getattr(row, "cmj_metric_flag_count", 0)),
            "cmj_flag_count_change": float(getattr(row, "cmj_flag_count_change", np.nan)),
            "cmj_overall_severity_score": float(getattr(row, "cmj_overall_severity_score", 0)),
            "cmj_overall_status": getattr(row, "cmj_overall_status", ""),
        })

    return pd.DataFrame(rows)

def add_workload_groups(
    data: pd.DataFrame,
    workload_col: str,
    position_specific: bool = False,
) -> pd.DataFrame:
    """Assign Q1-Q4 using the actual selected workload values and cutoffs."""
    out = data.copy()
    out["workload_group"] = pd.Series(pd.NA, index=out.index, dtype="string")
    labels = [
        "Q1 · Lowest workload",
        "Q2 · Lower-middle workload",
        "Q3 · Upper-middle workload",
        "Q4 · Highest workload",
    ]

    groups = (
        out.groupby("position_group", observed=True, dropna=False)
        if position_specific
        else [("Overall", out)]
    )
    for _, group in groups:
        values = pd.to_numeric(group[workload_col], errors="coerce")
        valid = values.dropna()
        if valid.empty:
            continue
        valid_idx = valid.index
        if len(valid) < 4:
            out.loc[valid_idx, "workload_group"] = "All workload"
            continue

        q1, q2, q3 = valid.quantile([0.25, 0.50, 0.75]).tolist()
        # Use the same raw-value cutoffs shown in the definitions table.
        assigned = np.select(
            [
                valid <= q1,
                (valid > q1) & (valid <= q2),
                (valid > q2) & (valid <= q3),
                valid > q3,
            ],
            labels,
            default="All workload",
        )
        out.loc[valid_idx, "workload_group"] = pd.Series(assigned, index=valid_idx, dtype="string")
    return out


def workload_quartile_cutoffs(
    data: pd.DataFrame,
    workload_col: str,
    position_specific: bool = False,
    workload_label: str | None = None,
) -> pd.DataFrame:
    """Return boundaries for the currently selected workload measure."""
    if workload_col not in data.columns:
        return pd.DataFrame()
    working = data.loc[pd.to_numeric(data[workload_col], errors="coerce").notna()].copy()
    if working.empty:
        return pd.DataFrame()
    groups = (
        working.groupby("position_group", observed=True, dropna=False)
        if position_specific
        else [("Overall selected sample", working)]
    )
    rows = []
    for label, group in groups:
        values = pd.to_numeric(group[workload_col], errors="coerce").dropna()
        if values.empty:
            continue
        q1, q2, q3 = values.quantile([0.25, 0.50, 0.75]).tolist()
        rows.append({
            "Workload measure": workload_label or workload_col,
            "Source column": workload_col,
            "Quartile scope": label,
            "n": len(values),
            "Minimum": values.min(),
            "Q1 upper cutoff (25th pct)": q1,
            "Q2 upper cutoff / median": q2,
            "Q3 upper cutoff (75th pct)": q3,
            "Maximum": values.max(),
            "Q1 definition": f"≤ {q1:,.1f}",
            "Q2 definition": f"> {q1:,.1f} to ≤ {q2:,.1f}",
            "Q3 definition": f"> {q2:,.1f} to ≤ {q3:,.1f}",
            "Q4 definition": f"> {q3:,.1f}",
        })
    return pd.DataFrame(rows)


def within_player_association(data: pd.DataFrame, workload_col: str, miss_col: str = "window_plan_misses", miss_label: str = "Plan misses") -> pd.DataFrame:
    """Simple within-player linear association; descriptive, not causal."""
    cols = ["player_key", "jump_change_pct", miss_col, workload_col, "days_since_previous_jump"]
    model = data[cols].dropna().copy()
    if len(model) < 30 or model["player_key"].nunique() < 3:
        return pd.DataFrame()

    for col in ["jump_change_pct", miss_col, workload_col, "days_since_previous_jump"]:
        model[col + "_wp"] = model[col] - model.groupby("player_key")[col].transform("mean")

    predictors = [miss_col + "_wp", workload_col + "_wp", "days_since_previous_jump_wp"]
    X = model[predictors].to_numpy(float)
    y = model["jump_change_pct_wp"].to_numpy(float)
    sds = np.nanstd(X, axis=0, ddof=1)
    sds[sds == 0] = 1.0
    Xz = X / sds
    Xdesign = np.column_stack([np.ones(len(Xz)), Xz])
    beta, *_ = np.linalg.lstsq(Xdesign, y, rcond=None)
    pred = Xdesign @ beta
    resid = y - pred
    dof = max(len(y) - Xdesign.shape[1], 1)
    sigma2 = float((resid @ resid) / dof)
    covariance = sigma2 * np.linalg.pinv(Xdesign.T @ Xdesign)
    se = np.sqrt(np.diag(covariance))[1:]
    names = [miss_label, "Total workload", "Days between jumps"]
    return pd.DataFrame({
        "Predictor": names,
        "Change per 1 SD": beta[1:],
        "Lower 95%": beta[1:] - 1.96 * se,
        "Upper 95%": beta[1:] + 1.96 * se,
        "N jump tests": len(model),
        "Players": model["player_key"].nunique(),
    })



