                sd_acc_text = f"{team_sd_acc:.1f}" if np.isfinite(team_sd_acc) else "N/A"
                st.caption(
                    f"Baseline = mean actual tagged-drill workload across all measured {rec_plan} player-days for {rec_team} "
                    f"({team_players_hist} historical players). HSR SD: {sd_hsr_text}; acceleration SD: {sd_acc_text}. "
                    "Game workload is not included in this team practice-dose baseline."
                )

                with st.expander("Adjustment sensitivity and decision trade-offs", expanded=False):
                    a1, a2 = st.columns(2)
                    hsr_diff_threshold = a1.number_input(
                        "Show adjustment when HSR differs by at least (m)",
                        min_value=0.0, value=10.0, step=5.0, key="team_rec_hsr_diff"
                    )
                    accel_diff_threshold = a2.number_input(
                        "Show adjustment when accelerations differ by at least",
                        min_value=0.0, value=3.0, step=1.0, key="team_rec_acc_diff"
                    )
                    p1, p2 = st.columns(2)
                    flag_penalty = p1.slider(
                        "Penalty per +10 percentage points of new-flag risk (CI %-points)",
                        min_value=0.0, max_value=1.0, value=0.25, step=0.05, key="team_rec_flag_penalty"
                    )
                    uncertainty_penalty = p2.slider(
                        "Penalty per 1%-point CI interval width",
                        min_value=0.0, max_value=0.5, value=0.15, step=0.05, key="team_rec_uncertainty_penalty"
                    )

                # Build the model table once. Player-specific states are scored
                # against cached position/level model pools below.
                with st.spinner("Building current player states and individualized recommendations..."):
                    rec_decisions = create_decision_outcome_table(rec_panel)
                    rec_audit = build_model_audit_dataset(rec_panel, rec_decisions, lookback_days=lb)

                    current_roster = latest_roster_rows.loc[
                        latest_roster_rows["team"].eq(rec_team)
                        & latest_roster_rows["position_group"].isin(selected_positions)
                    ][["player_key", "player_name", "position_group", "team"]].drop_duplicates("player_key")

                    ci_cache = {}
                    flag_cache = {}

                    def get_model_pool(pos):
                        """Prefer same-level+position, then same-level, same-position, organization."""
                        attempts = [
                            (rec_team, pos, "Same level + position"),
                            (rec_team, None, "Same level"),
                            (None, pos, "Same position"),
                            (None, None, "Organization"),
                        ]
                        ci_choice = None
                        flag_choice = None
                        for lev, pgrp, label in attempts:
                            key = (rec_plan, lb, lev or "", pgrp or "")
                            if key not in ci_cache:
                                ci_cache[key] = fit_dynamic_dose_model(
                                    rec_audit,
                                    scheduled_plan=rec_plan,
                                    lookback_days=lb,
                                    position_group=pgrp,
                                    level=lev,
                                    min_rows=35,
                                    bootstrap_iterations=40,
                                    seed=142,
                                )
                            ci_art, ci_hist, ci_info = ci_cache[key]
                            if ci_choice is None and ci_art is not None:
                                ci_choice = (ci_art, ci_hist, ci_info, label)

                            if key not in flag_cache:
                                flag_cache[key] = fit_recommendation_flag_model(
                                    rec_audit,
                                    scheduled_plan=rec_plan,
                                    lookback_days=lb,
                                    position_group=pgrp,
                                    level=lev,
                                    min_rows=60,
                                    bootstrap_iterations=30,
                                    seed=143,
                                )
                            fl_art, fl_hist, fl_info = flag_cache[key]
                            if flag_choice is None and fl_art is not None:
                                flag_choice = (fl_art, fl_hist, fl_info, label)

                            if ci_choice is not None and flag_choice is not None:
                                break
                        return ci_choice, flag_choice

                    exception_rows = []
                    no_model_rows = []
                    supported_same_rows = 0

                    for rr in current_roster.sort_values(["position_group", "player_name"]).itertuples(index=False):
                        state_pack = latest_recommendation_state(rec_panel, rr.player_key, lookback_days=lb)
                        if state_pack is None:
                            no_model_rows.append({"Player": rr.player_name, "Position": rr.position_group, "Reason": "Current state unavailable"})
                            continue
                        current_state = dict(state_pack["state"])
                        ci_choice, flag_choice = get_model_pool(rr.position_group)
                        if ci_choice is None:
                            no_model_rows.append({"Player": rr.player_name, "Position": rr.position_group, "Reason": "CI dose model unavailable"})
                            continue

                        ci_artifact, ci_history, ci_info, ci_pool_label = ci_choice
                        hsr_low = max(0.0, float(ci_history["actual_hsr_m"].quantile(0.05)))
                        hsr_high = float(ci_history["actual_hsr_m"].quantile(0.95))
                        acc_low = max(0.0, float(ci_history["actual_accelerations"].quantile(0.05)))
                        acc_high = float(ci_history["actual_accelerations"].quantile(0.95))

                        # Ensure the team baseline is represented in the candidate
                        # range while keeping the grid within observed dose territory.
                        hsr_values = np.unique(np.round(np.r_[
                            np.linspace(hsr_low, max(hsr_low + 10.0, hsr_high), 13),
                            np.clip(team_avg_hsr, hsr_low, max(hsr_low + 10.0, hsr_high)),
                        ], 1))
                        accel_values = np.unique(np.round(np.r_[
                            np.linspace(acc_low, max(acc_low + 2.0, acc_high), 11),
                            np.clip(team_avg_acc, acc_low, max(acc_low + 2.0, acc_high)),
                        ], 1))

                        ci_grid = predict_dose_grid(ci_artifact, ci_history, current_state, hsr_values, accel_values)
                        ci_grid["Execution category"] = [
                            candidate_execution_label(rec_plan, h, a, thresholds)
                            for h, a in zip(ci_grid["HSR target (m)"], ci_grid["Acceleration target"])
                        ]

                        current_preflagged = bool(float(current_state.get("cmj_any_flag_last", 0.0) or 0.0) > 0)
                        flag_artifact = None
                        flag_history = None
                        flag_pool_label = "N/A"
                        if flag_choice is not None:
                            flag_artifact, flag_history, flag_info, flag_pool_label = flag_choice

                        if flag_artifact is not None and not current_preflagged:
                            flag_grid = predict_flag_risk_grid(
                                flag_artifact,
                                flag_history,
                                current_state,
                                ci_grid[["HSR target (m)", "Acceleration target"]],
                            )
                            combined = ci_grid.merge(flag_grid, on=["HSR target (m)", "Acceleration target"], how="left")
                            combined["Combined support n"] = combined[["Historical support n", "Flag historical support n"]].min(axis=1)
                            combined["Combined support"] = [
                                min([a, b], key=_support_rank)
                                for a, b in zip(combined["Support"], combined["Flag support"])
                            ]
                        else:
                            combined = ci_grid.copy()
                            combined["Predicted new-flag risk %"] = np.nan
                            combined["Flag risk lower 95%"] = np.nan
                            combined["Flag risk upper 95%"] = np.nan
                            combined["Combined support n"] = combined["Historical support n"]
                            combined["Combined support"] = combined["Support"]

                        combined["CI interval width"] = combined["Upper 95%"] - combined["Lower 95%"]
                        risk_component = combined["Predicted new-flag risk %"].fillna(0.0) / 10.0
                        combined["Decision score"] = (
                            combined["Expected next CI change (%)"]
                            - float(uncertainty_penalty) * combined["CI interval width"]
                            - float(flag_penalty) * risk_component
                        )

                        # A candidate is selectable only if the model produced a finite score.
                        # This prevents idxmax() from returning NaN when a player's current
                        # state contains not-yet-established CMJ values.
                        combined["Decision score"] = pd.to_numeric(combined["Decision score"], errors="coerce")
                        finite_candidates = combined.loc[np.isfinite(combined["Decision score"])].copy()
                        supported = finite_candidates.loc[finite_candidates["Combined support"].isin(["Strong", "Moderate"])].copy()
                        fallback = finite_candidates.loc[finite_candidates["Combined support"].eq("Weak")].copy()
                        choice_pool = supported if not supported.empty else fallback
                        if choice_pool.empty:
                            reason = "No finite candidate score" if finite_candidates.empty else "No candidate with historical support"
                            no_model_rows.append({
                                "Player": rr.player_name,
                                "Position": rr.position_group,
                                "Reason": reason,
                            })
                            continue
                        best_idx = choice_pool["Decision score"].idxmax(skipna=True)
                        if pd.isna(best_idx):
                            no_model_rows.append({
                                "Player": rr.player_name,
                                "Position": rr.position_group,
                                "Reason": "No finite candidate score",
                            })
                            continue
                        best = choice_pool.loc[best_idx]

                        # Nearest modeled candidate to the team average, used to
                        # compare the model's individual adjustment with normal team practice.
                        scale_hsr = max(_finite_float(ci_history["actual_hsr_m"].std(), 1.0), 1.0)
                        scale_acc = max(_finite_float(ci_history["actual_accelerations"].std(), 1.0), 1.0)
                        baseline_dist = (
                            (pd.to_numeric(combined["HSR target (m)"], errors="coerce") - team_avg_hsr).abs() / scale_hsr
                            + (pd.to_numeric(combined["Acceleration target"], errors="coerce") - team_avg_acc).abs() / scale_acc
                        ).replace([np.inf, -np.inf], np.nan)
                        valid_baseline = baseline_dist.dropna()
                        if valid_baseline.empty:
                            no_model_rows.append({
                                "Player": rr.player_name,
                                "Position": rr.position_group,
                                "Reason": "Team baseline could not be scored",
                            })
                            continue
                        baseline_row = combined.loc[valid_baseline.idxmin()]

                        delta_hsr = float(best["HSR target (m)"] - team_avg_hsr)
                        delta_acc = float(best["Acceleration target"] - team_avg_acc)
                        meaningfully_different = (
                            abs(delta_hsr) >= float(hsr_diff_threshold)
                            or abs(delta_acc) >= float(accel_diff_threshold)
                        )

                        if not meaningfully_different:
                            supported_same_rows += 1
                            continue

                        if delta_hsr < -float(hsr_diff_threshold) and delta_acc < -float(accel_diff_threshold):
                            adjustment = "Reduce HSR + accelerations"
                        elif delta_hsr > float(hsr_diff_threshold) and delta_acc > float(accel_diff_threshold):
                            adjustment = "Increase HSR + accelerations"
                        elif delta_hsr <= -float(hsr_diff_threshold):
                            adjustment = "Reduce HSR"
                        elif delta_hsr >= float(hsr_diff_threshold):
                            adjustment = "Increase HSR"
                        elif delta_acc <= -float(accel_diff_threshold):
                            adjustment = "Reduce accelerations"
                        elif delta_acc >= float(accel_diff_threshold):
                            adjustment = "Increase accelerations"
                        else:
                            adjustment = "Modify dose"

                        ci_gain_vs_team = float(best["Expected next CI change (%)"] - baseline_row["Expected next CI change (%)"])
                        if np.isfinite(best.get("Predicted new-flag risk %", np.nan)) and np.isfinite(baseline_row.get("Predicted new-flag risk %", np.nan)):
                            risk_change = float(best["Predicted new-flag risk %"] - baseline_row["Predicted new-flag risk %"])
                        else:
                            risk_change = np.nan

                        status_map = {0: "None", 1: "MONITOR", 2: "REVIEW"}
                        sev = int(np.clip(round(_finite_float(current_state.get("cmj_overall_severity_score_last", 0.0), 0.0)), 0, 2))
                        exception_rows.append({
                            "Player": rr.player_name,
                            "Position": rr.position_group,
                            "CMJ status": status_map.get(sev, "None"),
                            f"Prior {lb}d high-intensity (m)": _finite_float(current_state.get(f"prior_high_intensity_proxy_m_{lb}d", 0.0), 0.0),
                            "Team HSR (m)": team_avg_hsr,
                            "Recommended HSR (m)": float(best["HSR target (m)"]),
                            "Δ HSR (m)": delta_hsr,
                            "Team accelerations": team_avg_acc,
                            "Recommended accelerations": float(best["Acceleration target"]),
                            "Δ accelerations": delta_acc,
                            "Adjustment": adjustment,
                            "Execution category": best["Execution category"],
                            "Expected CI change %": float(best["Expected next CI change (%)"]),
                            "CI gain vs team baseline pp": ci_gain_vs_team,
                            "Predicted new-flag risk %": float(best.get("Predicted new-flag risk %", np.nan)),
                            "Flag-risk change vs team pp": risk_change,
                            "Historical support": best["Combined support"],
                            "Support n": int(best["Combined support n"]),
                            "Model pool": ci_pool_label,
                        })

                st.markdown("### Individual adjustments from the team plan")
                st.caption(
                    f"Only players whose supported recommendation differs from the {rec_team} {rec_plan} average by at least "
                    f"{hsr_diff_threshold:.0f} m HSR **or** {accel_diff_threshold:.0f} accelerations are shown. "
                    "Players not listed should default to the team average under the current model settings."
                )

                if exception_rows:
                    exceptions = pd.DataFrame(exception_rows)
                    # Put reductions / larger absolute changes near the top.
                    exceptions["_change_magnitude"] = (
                        exceptions["Δ HSR (m)"].abs() / max(float(hsr_diff_threshold), 1.0)
                        + exceptions["Δ accelerations"].abs() / max(float(accel_diff_threshold), 1.0)
                    )
                    exceptions = exceptions.sort_values(
                        ["CMJ status", "_change_magnitude"],
                        ascending=[False, False]
                    ).drop(columns="_change_magnitude")
                    st.dataframe(
                        exceptions.style.format({
                            f"Prior {lb}d high-intensity (m)": "{:.1f}",
                            "Team HSR (m)": "{:.1f}",
                            "Recommended HSR (m)": "{:.1f}",
                            "Δ HSR (m)": "{:+.1f}",
                            "Team accelerations": "{:.1f}",
                            "Recommended accelerations": "{:.1f}",
                            "Δ accelerations": "{:+.1f}",
                            "Expected CI change %": "{:+.2f}",
                            "CI gain vs team baseline pp": "{:+.2f}",
                            "Predicted new-flag risk %": "{:.1f}",
                            "Flag-risk change vs team pp": "{:+.1f}",
                        }),
                        use_container_width=True,
                        hide_index=True,
                    )
                    st.download_button(
                        "Download individual adjustment table",
                        exceptions.to_csv(index=False).encode("utf-8"),
                        file_name=f"{rec_team}_{rec_plan.lower()}_individual_adjustments_{lb}d.csv".replace(" ", "_"),
                        mime="text/csv",
                        key="download_team_rec_adjustments",
                    )
                else:
                    st.success("No player has a supported individualized adjustment that exceeds the current difference thresholds. Use the team average for everyone.")

                s1, s2, s3 = st.columns(3)
                s1.metric("Current GPS-roster players", f"{len(current_roster):,}")
                s2.metric("Players with individual adjustment", f"{len(exception_rows):,}")
                s3.metric("Players staying on team baseline", f"{supported_same_rows:,}")

                if no_model_rows:
                    with st.expander(f"Players without a supported recommendation ({len(no_model_rows)})", expanded=False):
                        st.dataframe(pd.DataFrame(no_model_rows), use_container_width=True, hide_index=True)

                st.info(
                    "The displayed team average is the default plan. Individual rows are exceptions only. A row does not mean the alternative is causally proven; "
                    "it means the historical models found a supported dose with a better selected trade-off between expected CI response, uncertainty, and new-flag risk."
                )


