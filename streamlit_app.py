def frame(values):
    if not values: return pd.DataFrame()
    w=max(map(len,values)); rows=[list(r)+[""]*(w-len(r)) for r in values]
    header=[clean(x) for x in rows[0]]; data=rows[1:]
    keep=[i for i,h in enumerate(header) if h or any(clean(r[i]) for r in data)]
    names=[]; seen={}
    for i in keep:
        h=header[i] or f"unnamed_{i+1}"; seen[h]=seen.get(h,0)+1
        names.append(h if seen[h]==1 else f"{h}_{seen[h]}")
    return pd.DataFrame([[r[i] for i in keep] for r in data],columns=names)

def read_tab(book,tab,a1):
    values=book.worksheet(tab).get(a1,value_render_option="UNFORMATTED_VALUE",
                                    date_time_render_option="SERIAL_NUMBER",pad_values=True)
    return frame(list(values))

def require(df,cols,label):
    missing=[c for c in cols if c not in df.columns]
    if missing: raise ValueError(f"{label} missing {missing}. Available: {list(df.columns)}")

def prep_roster(raw):
    require(raw,["Athlete","Team","Position"],ROSTER_TAB)
    cols=[c for c in ["Athlete","Team","Position","ATHLETE ID","Height"] if c in raw]
    r=raw[cols].rename(columns={"Athlete":"player_name","Team":"roster_team","Position":"roster_position",
                                "ATHLETE ID":"roster_athlete_id","Height":"roster_height"}).copy()
    r["player_key"]=r.player_name.map(player_key); r=r[r.player_key.ne("")]
    agg={c:first_nonblank for c in r.columns if c!="player_key"}
    r=r.groupby("player_key",as_index=False).agg(agg)
    r["roster_position_group"]=r.roster_position.map(pos_group)
    return r

def prep_jump(raw):
    require(raw,["Athlete","Date"],JUMP_TAB)
    mp={k:v for k,v in JUMP_RENAME.items() if k in raw}
    j=raw[list(mp)].rename(columns=mp).copy()
    j["player_key"]=j.player_name.map(player_key); j["date"]=parse_dates(j.date)
    j=j[j.player_key.ne("") & j.date.notna()].drop_duplicates()
    nums=[c for c in JUMP_NUMERIC if c in j]
    for c in nums: j[c]=pd.to_numeric(j[c],errors="coerce")
    agg={"player_name":first_nonblank,**{c:"mean" for c in nums}}
    for c in ["athlete_id_jump","jump_team_observed","jump_position_observed"]:
        if c in j: agg[c]=mode_nonblank if "observed" in c else first_nonblank
    d=j.groupby(["player_key","date"],as_index=False).agg(agg)
    n=j.groupby(["player_key","date"]).size().rename("jump_n_tests").reset_index()
    d=d.merge(n,on=["player_key","date"],how="left"); d["jump_observed"]=1
    d=d.sort_values(["player_key","date"]).reset_index(drop=True)
    for c in [x for x in READINESS if x in d]:
        prev=d.groupby("player_key",sort=False)[c].transform(lambda s:s.shift(1).rolling(3,min_periods=2).mean())
        d[f"{c}_prev3_test_mean"]=prev
        d[f"{c}_vs_prev3_test_pct"]=np.where(prev.abs()>1e-12,100*(d[c]-prev)/prev,np.nan)
    d = add_cmj_reproduction_flags(d)
    return d

def aggregate_session(g):
    """Aggregate one player-session using only explicitly tagged field drills.

    A STATSports row contributes to practice workload only when ``drill_name``
    is populated with a real drill tag. Blank drill rows, session summaries,
    and lift-only tags are retained only as evidence that a STATSports session
    existed; none of their workload values enter the player-day totals.
    """
    out={}
    out["statsports_session_observed"]=1

    drill_clean=g["drill_name"].map(clean)
    drill_key=drill_clean.str.casefold()
    is_named=drill_clean.ne("")
    is_summary=drill_key.isin(SUMMARY_DRILLS)
    is_lift=drill_clean.map(is_lift_drill)
    tagged_mask=is_named & ~is_summary & ~is_lift
    workload=g.loc[tagged_mask].copy()

    out["gps_on_field_observed_session"]=int(not workload.empty)
    for c in GPS_MAX:
        x=pd.to_numeric(workload[c],errors="coerce")
        out[c]=x.max() if x.notna().any() else np.nan
    for c in GPS_SUM:
        x=pd.to_numeric(workload[c],errors="coerce")
        out[c]=x.sum() if x.notna().any() else np.nan

    tagged_names=workload["drill_name"].map(clean)
    out["gps_n_drills"]=int(tagged_names[tagged_names.ne("")].nunique())
    out["gps_team_observed"]=mode_nonblank(g.gps_team_observed)
    out["planned_day_type_session"]=mode_nonblank(g.planned_day_type_session)
    out["player_name"]=first_nonblank(g.player_name)
    return out

def prep_gps(raw):
    req=["date","session_name","player_name","drill_name",*GPS_RENAME]
    require(raw,req,GPS_TAB)
    g=raw[req].rename(columns=GPS_RENAME).copy()
    g["player_key"]=g.player_name.map(player_key); g["date"]=parse_dates(g.date)
    g=g[g.player_key.ne("") & g.date.notna()].drop_duplicates()
    for c in GPS_MAX+GPS_SUM: g[c]=pd.to_numeric(g[c],errors="coerce")
    g["session_name"]=g.session_name.map(clean); g["drill_name"]=g.drill_name.map(clean)
    g["gps_team_observed"]=g.session_name.map(infer_team)
    g["planned_day_type_session"]=g.session_name.map(infer_day_type)
    rows=[]; keys=["player_key","date","session_name"]
    for k,x in g.groupby(keys,sort=False,dropna=False):
        row=dict(zip(keys,k)); row.update(aggregate_session(x)); rows.append(row)
    s=pd.DataFrame(rows)
    if s.empty: return s

    named={
        "player_name":("player_name",first_nonblank),
        "gps_team_observed":("gps_team_observed",mode_nonblank),
        "statsports_n_sessions":("session_name","nunique"),
        "gps_n_sessions":("gps_on_field_observed_session","sum"),
        "gps_n_drills":("gps_n_drills","sum"),
        "planned_day_type":("planned_day_type_session",highest_day_type),
        "statsports_observed":("statsports_session_observed","max"),
        "gps_observed":("gps_on_field_observed_session","max"),
    }
    named.update({c:(c,numeric_max) for c in GPS_MAX})
    named.update({c:(c,numeric_sum) for c in GPS_SUM})
    d=s.groupby(["player_key","date"],as_index=False).agg(**named)

    extra=s.groupby(["player_key","date"],as_index=False).agg(
        statsports_session_names=("session_name",join_unique),
        planned_day_types_seen=("planned_day_type_session",join_unique),
        planned_day_type_n_unique=("planned_day_type_session",count_nonblank_unique))
    field_names=(s.loc[s.gps_on_field_observed_session.eq(1)]
                   .groupby(["player_key","date"],as_index=False)
                   .agg(gps_session_names=("session_name",join_unique)))
    d=d.merge(extra,on=["player_key","date"],how="left")
    d=d.merge(field_names,on=["player_key","date"],how="left")
    for c in ["statsports_observed","gps_observed"]:
        d[c]=d[c].fillna(0).astype("int8")
    d["planned_day_type_3level"]=d.planned_day_type.map(three_level_day_type)
    d["planned_day_type_numeric"]=d.planned_day_type_3level.map(DAY_TYPE_LEVEL)
    d["planned_day_type_observed"]=d.planned_day_type.notna().astype("int8")
    d["planned_day_type_conflict"]=d.planned_day_type_n_unique.gt(1).astype("int8")
    return d.sort_values(["player_key","date"]).reset_index(drop=True)

def prep_pp_sprint(raw):
    """Return daily game load and one row per player-month for monthly performance metrics."""
    require(raw,["batter","game_date"],PP_SPRINT_TAB)
    cols=[c for c in PP_RENAME if c in raw.columns]
    q=raw[cols].rename(columns={c:PP_RENAME[c] for c in cols}).copy()
    q["player_key"]=q.player_name.map(player_key); q["date"]=parse_dates(q.date)
    q=q[q.player_key.ne("") & q.date.notna()].drop_duplicates()
    if q.empty:
        return q, pd.DataFrame(columns=["player_key","performance_month",*PP_MONTHLY_METRICS])
    if "game_pk" not in q: q["game_pk"]=""
    q["game_pk"]=q.game_pk.map(clean_game_pk)
    numeric_cols=[
        "game_max_effort_runs","game_max_effort_distance_yards","game_distance_covered_yards",
        *PP_MONTHLY_METRICS,
    ]
    for c in numeric_cols:
        if c not in q: q[c]=np.nan
        q[c]=pd.to_numeric(q[c],errors="coerce")
    if "game_team_observed" not in q: q["game_team_observed"]=np.nan

    # These are full calendar-month summaries repeated on each PP_Sprint game row.
    # Collapse them to one player-month record before joining to the daily panel.
    q["performance_month"]=q["date"].dt.to_period("M")
    monthly_named={c:(c,numeric_max) for c in PP_MONTHLY_METRICS}
    monthly=q.groupby(["player_key","performance_month"],as_index=False).agg(**monthly_named)
    monthly["monthly_performance_observed"]=monthly[PP_MONTHLY_METRICS].notna().any(axis=1).astype("int8")

    named={
        "player_name":("player_name",first_nonblank),
        "game_n_games":("game_pk",count_games),
        "game_pks":("game_pk",join_unique),
        "game_team_observed":("game_team_observed",mode_nonblank),
        "game_max_effort_runs":("game_max_effort_runs",numeric_sum),
        "game_max_effort_distance_yards":("game_max_effort_distance_yards",numeric_sum),
        "game_distance_covered_yards":("game_distance_covered_yards",numeric_sum),
    }
    d=q.groupby(["player_key","date"],as_index=False).agg(**named)
    d["game_max_effort_distance_m"]=pd.to_numeric(d.game_max_effort_distance_yards,errors="coerce")*0.9144
    d["game_distance_covered_m"]=pd.to_numeric(d.game_distance_covered_yards,errors="coerce")*0.9144
    d["game_observed"]=1
    d["game_workload_observed"]=d[[
        "game_max_effort_runs","game_max_effort_distance_yards","game_distance_covered_yards"
    ]].notna().any(axis=1).astype("int8")
    return d.sort_values(["player_key","date"]).reset_index(drop=True), monthly

def date_limits(j,g,q):
    dates=[]
    if not j.empty: dates += j.date.dropna().tolist()
    if not g.empty: dates += g.date.dropna().tolist()
    if not q.empty: dates += q.date.dropna().tolist()
    if not dates: raise ValueError("No valid dates found.")
    start=pd.Timestamp(START_DATE).normalize() if START_DATE else pd.Timestamp(min(dates)).normalize()
    end=pd.Timestamp(END_DATE).normalize() if END_DATE else pd.Timestamp(max(dates)).normalize()
    if end<start: raise ValueError("END_DATE is before START_DATE")
    return start,end

def add_rolling(p):
    key=p.player_key

    prior_obs=p.gps_observed.groupby(key,sort=False).shift(1).fillna(0)
    for w in (3,7,14,28):
        p[f"gps_prior_{w}d_observed_days"]=prior_obs.groupby(key,sort=False).transform(lambda s:s.rolling(w,min_periods=1).sum())
        p[f"gps_prior_{w}d_coverage"]=p[f"gps_prior_{w}d_observed_days"]/w
    for c in [x for x in GPS_SUM if x in p]:
        prior=p[c].fillna(0).groupby(key,sort=False).shift(1).fillna(0)
        for w in (3,7,14,28):
            p[f"{c}_prior_{w}d_observed_sum"]=prior.groupby(key,sort=False).transform(lambda s:s.rolling(w,min_periods=1).sum())

    prior_game=p.game_observed.groupby(key,sort=False).shift(1).fillna(0)
    for w in (3,7,14,28):
        p[f"game_prior_{w}d_days"]=prior_game.groupby(key,sort=False).transform(lambda s:s.rolling(w,min_periods=1).sum())
    for c in [x for x in GAME_LOAD_SUM if x in p]:
        prior=p[c].fillna(0).groupby(key,sort=False).shift(1).fillna(0)
        for w in (3,7,14,28):
            p[f"{c}_prior_{w}d_sum"]=prior.groupby(key,sort=False).transform(lambda s:s.rolling(w,min_periods=1).sum())

    prior_field=p.on_field_load_observed.groupby(key,sort=False).shift(1).fillna(0)
    for w in (3,7,14,28):
        p[f"on_field_prior_{w}d_observed_days"]=prior_field.groupby(key,sort=False).transform(lambda s:s.rolling(w,min_periods=1).sum())
        for c in ["on_field_total_distance_m","on_field_high_intensity_distance_proxy_m"]:
            prior=p[c].fillna(0).groupby(key,sort=False).shift(1).fillna(0)
            p[f"{c}_prior_{w}d_sum"]=prior.groupby(key,sort=False).transform(lambda x:x.rolling(w,min_periods=1).sum())
    return p

def build_player_date(jump_raw,gps_raw,roster_raw,pp_raw):
    r=prep_roster(roster_raw); j=prep_jump(jump_raw); g=prep_gps(gps_raw); q, monthly_perf=prep_pp_sprint(pp_raw)
    start,end=date_limits(j,g,q)
    j=j[j.date.between(start,end)].copy(); g=g[g.date.between(start,end)].copy(); q=q[q.date.between(start,end)].copy()
    players=set(j.player_key)|set(g.player_key)|set(q.player_key)
    if INCLUDE_ROSTER_PLAYERS_WITHOUT_DATA: players|=set(r.player_key)
    players.discard("")
    if not players: raise ValueError("No players remained after date filtering")
    p=pd.MultiIndex.from_product([sorted(players),pd.date_range(start,end,freq="D")],names=["player_key","date"]).to_frame(index=False)
    names=pd.concat([r[["player_key","player_name"]],j[["player_key","player_name"]],g[["player_key","player_name"]],q[["player_key","player_name"]]],ignore_index=True)
    names=names[names.player_key.ne("")].drop_duplicates("player_key",keep="first")
    p=p.merge(names,on="player_key",how="left").merge(r,on="player_key",how="left",suffixes=("","_roster"))
    if "player_name_roster" in p: p.player_name=p.player_name.fillna(p.player_name_roster); p=p.drop(columns="player_name_roster")
    p=p.merge(g,on=["player_key","date"],how="left",suffixes=("","_gps"))
    if "player_name_gps" in p: p.player_name=p.player_name.fillna(p.player_name_gps); p=p.drop(columns="player_name_gps")
    p=p.merge(q,on=["player_key","date"],how="left",suffixes=("","_game"))
    if "player_name_game" in p: p.player_name=p.player_name.fillna(p.player_name_game); p=p.drop(columns="player_name_game")

    # Add the full-month source metrics for descriptive use, plus an exact
    # prior-calendar-month version for leakage-safe predictive modeling.
    p["_performance_month"]=p["date"].dt.to_period("M")
    current_month=monthly_perf.copy()
    p=p.merge(
        current_month,
        left_on=["player_key","_performance_month"],
        right_on=["player_key","performance_month"],
        how="left",
    ).drop(columns=["performance_month"],errors="ignore")
    prior_month=monthly_perf.copy()
    prior_month["prior_month_performance_source_month"]=prior_month["performance_month"].astype(str)
    prior_month["performance_month"]=prior_month["performance_month"]+1
    prior_month=prior_month.rename(columns={
        c:f"prior_month_{c.removeprefix('monthly_')}" for c in PP_MONTHLY_METRICS
    } | {"monthly_performance_observed":"prior_month_performance_observed"})
    p=p.merge(
        prior_month,
        left_on=["player_key","_performance_month"],
        right_on=["player_key","performance_month"],
        how="left",
    ).drop(columns=["performance_month","_performance_month"],errors="ignore")
    for c in ["monthly_performance_observed","prior_month_performance_observed"]:
        if c not in p: p[c]=0
        p[c]=p[c].fillna(0).astype("int8")

    p=p.merge(j,on=["player_key","date"],how="left",suffixes=("","_jump"))
    if "player_name_jump" in p: p.player_name=p.player_name.fillna(p.player_name_jump); p=p.drop(columns="player_name_jump")
    p=p.sort_values(["player_key","date"]).reset_index(drop=True)
    for c in ["statsports_observed","gps_observed","game_observed","game_workload_observed","jump_observed"]:
        if c not in p: p[c]=0
        p[c]=p[c].fillna(0).astype("int8")
    p["gps_missing"]=1-p.gps_observed
    p["jump_missing"]=1-p.jump_observed
    p["game_day"]=p.game_observed

    # Define each player's observed season window. This prevents dates before a
    # player arrives or after their last observation from being automatically
    # classified as Low.
    any_observed=p["statsports_observed"].eq(1) | p["game_observed"].eq(1) | p["jump_observed"].eq(1)
    p["first_any_observation"]=p["date"].where(any_observed).groupby(p["player_key"],sort=False).transform("min")
    p["last_any_observation"]=p["date"].where(any_observed).groupby(p["player_key"],sort=False).transform("max")
    p["within_observed_window"]=(
        p["first_any_observation"].notna()
        & p["date"].ge(p["first_any_observation"])
        & p["date"].le(p["last_any_observation"])
    ).astype("int8")
    p["player_has_gps"]=p.groupby("player_key",sort=False)["gps_observed"].transform("max").astype("int8")
    p["player_has_game"]=p.groupby("player_key",sort=False)["game_observed"].transform("max").astype("int8")
    p["player_has_jump"]=p.groupby("player_key",sort=False)["jump_observed"].transform("max").astype("int8")

    # ------------------------------------------------------------------
    # GPS-ROSTER ASSIGNMENT
    # ------------------------------------------------------------------
    # The STATSports session name is the roster source of truth. A player's
    # affiliate changes when a GPS session name changes affiliate. On dates
    # without a GPS session, carry the most recently observed GPS roster
    # forward. Dates before the first GPS session are assigned to the first GPS
    # roster seen that season so early CMJ tests can still be attributed to the
    # roster the player entered in the GPS data. We intentionally do NOT use
    # Master Roster, Jump Data, or PP_Sprint team fields for affiliate assignment.
    gps_team=(
        p["gps_team_observed"].copy()
        if "gps_team_observed" in p
        else pd.Series(np.nan,index=p.index,dtype="object")
    )
    gps_team=gps_team.map(lambda x: clean(x) if pd.notna(x) else np.nan)
    gps_team=gps_team.replace("",np.nan)
    gps_ffill=gps_team.groupby(p["player_key"],sort=False).ffill()
    gps_bfill=gps_team.groupby(p["player_key"],sort=False).bfill()
    p["team_observed"]=gps_team
    p["team"]=gps_ffill.combine_first(gps_bfill)
    p["team_assignment_source"]=np.select(
        [
            gps_team.notna(),
            gps_team.isna() & gps_ffill.notna(),
            gps_team.isna() & gps_ffill.isna() & gps_bfill.notna(),
        ],
        [
            "gps_session_name_same_day",
            "most_recent_prior_gps_session",
            "first_gps_session_backfill",
        ],
        default="unassigned_no_gps_roster",
    )
    # Treat placeholder position labels as missing so values such as "NA"
    # do not overwrite a valid roster position and remove a player from the
    # position-player panel after their first jump test.
    raw_position_observed=(
        p["jump_position_observed"]
        if "jump_position_observed" in p
        else pd.Series(np.nan,index=p.index,dtype="object")
    )
    placeholder_positions={"", "NA", "N/A", "NONE", "UNKNOWN", "NAN", "-", "--"}
    raw_position_observed=raw_position_observed.map(
        lambda x: np.nan if clean(x).upper() in placeholder_positions else clean(x)
    )
    observed_position_group=raw_position_observed.map(pos_group)
    p["position_observed"]=raw_position_observed.where(
        observed_position_group.isin({"P","C","INF","OF"})
    )
    p["position"]=(
        p.groupby("player_key",sort=False).position_observed
        .transform(lambda s:s.ffill())
        .fillna(p.get("roster_position"))
    )
    p["position_group"]=p.position.map(pos_group).fillna(p.get("roster_position_group"))


    # Preserve whether the day type came from an actual session name. Missing
    # STATSports days may then be treated as Low without pretending the tag was
    # directly observed. GPS metrics remain blank and gps_missing remains 1.
    for c in ["planned_day_type_observed","planned_day_type_conflict"]:
        if c not in p: p[c]=0
        p[c]=p[c].fillna(0).astype("int8")
    p["planned_day_type_source"]=np.where(
        p["planned_day_type_observed"].eq(1), "session_name", "missing"
    )
    p["planned_day_type_assumed"]=0
    if ASSUME_NO_GPS_AS_LOW:
        # Do not overwrite an observed High/Moderate/Low/Recovery session tag.
        # The Low assumption is only for dates with no valid tagged-drill GPS,
        # no game workload, and no day type visible in a session name.
        assume_low=(
            p["gps_observed"].eq(0)
            & p["game_observed"].eq(0)
            & p["planned_day_type_observed"].eq(0)
        )
        if NO_GPS_LOW_SCOPE == "within_observed_window":
            assume_low &= p["within_observed_window"].eq(1)
        elif NO_GPS_LOW_SCOPE != "all_panel_days":
            raise ValueError(
                'NO_GPS_LOW_SCOPE must be "within_observed_window" or "all_panel_days"'
            )
        p.loc[assume_low,"planned_day_type"]="Low"
        p.loc[assume_low,"planned_day_type_3level"]="Low"
        p.loc[assume_low,"planned_day_type_numeric"]=DAY_TYPE_LEVEL["Low"]
        p.loc[assume_low,"planned_day_type_source"]="assumed_no_practice_or_game_data"
        p.loc[assume_low,"planned_day_type_assumed"]=1
    p["planned_day_type_assumed"]=p["planned_day_type_assumed"].astype("int8")

    # Keep practice GPS and game tracking separate, then provide transparent
    # combined daily fields for models that need total on-field exposure.
    p["on_field_load_observed"]=(p["gps_observed"].eq(1) | p["game_observed"].eq(1)).astype("int8")
    gps_total=numeric_series(p,"gps_total_distance_m")
    game_total=numeric_series(p,"game_distance_covered_m")
    gps_high=numeric_series(p,"gps_hsr_distance_m")
    game_high=numeric_series(p,"game_max_effort_distance_m")
    p["on_field_total_distance_m"]=pd.concat([gps_total,game_total],axis=1).sum(axis=1,min_count=1)
    p["on_field_high_intensity_distance_proxy_m"]=pd.concat([gps_high,game_high],axis=1).sum(axis=1,min_count=1)
    p["on_field_workload_assumed_low"]=p["planned_day_type_assumed"].astype("int8")
    p["on_field_workload_source"]=np.select(
        [
            p["gps_observed"].eq(1) & p["game_observed"].eq(1),
            p["gps_observed"].eq(1),
            p["game_observed"].eq(1),
            p["on_field_workload_assumed_low"].eq(1),
            p["within_observed_window"].eq(0),
        ],
        ["practice_gps_and_game","practice_gps","game_tracking","assumed_low_no_data","outside_observed_window"],
        default="missing",
    )
    if POSITION_GROUP_FILTER:
        p=p[p.position_group.isin(POSITION_GROUP_FILTER)].copy()
        if p.empty: raise ValueError(f"No rows after POSITION_GROUP_FILTER={POSITION_GROUP_FILTER}")
    p["player_date_id"]=p.player_key+"__"+p.date.dt.strftime("%Y-%m-%d")
    p["day_of_week"]=p.date.dt.day_name(); p["day_of_week_number"]=p.date.dt.dayofweek+1
    p["week_start"]=p.date-pd.to_timedelta(p.date.dt.dayofweek,unit="D")
