@dataclass(frozen=True)
class Thresholds:
    very_high_hsr: float = 160.0
    high_hsr: float = 80.0
    high_accels: float = 25.0
    moderate_hsr_min: float = 0.0
    moderate_hsr_max: float = 60.0
    moderate_accels_min: float = 15.0
    moderate_accels_max_exclusive: float = 30.0
    low_hsr_max_exclusive: float = 40.0
    low_accels_max_exclusive: float = 15.0


def safe_numeric(series: pd.Series, default: float | None = None) -> pd.Series:
    out = pd.to_numeric(series, errors="coerce")
    if default is not None:
        out = out.fillna(default)
    return out


def safe_rate(numerator: float | int, denominator: float | int) -> float:
    if denominator is None or denominator == 0 or pd.isna(denominator):
        return np.nan
    return float(numerator) / float(denominator)


def ordered_levels(values: Iterable[str]) -> list[str]:
    cleaned = [str(v) for v in values if pd.notna(v)]
    rank = {name: i for i, name in enumerate(LEVEL_ORDER)}
    return sorted(set(cleaned), key=lambda x: (rank.get(x, 999), x.lower()))


