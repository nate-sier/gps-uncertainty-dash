def build_dose_response_table(
    player_date_df: pd.DataFrame,
    decision_df: pd.DataFrame,
    lookback_days: int = 5,
) -> pd.DataFrame:
    """Add leakage-safe pre-practice state features to the decision table.

    The preceding window excludes the decision date. Actual HSR/accelerations are
    retained as the realized dose, while the outcome is the next jump 2-7 days
    later. This supports a first dynamic dose-response analysis within each
    scheduled/planned day type.
    """
    panel = player_date_df.sort_values(["player_key", "date"]).copy()
    key = panel["player_key"]

    source_map = {
        "gps_hsr_distance_m": "prior_practice_hsr_m",
        "gps_n_accelerations": "prior_practice_accelerations",
        "gps_total_distance_m": "prior_practice_total_distance_m",
        "game_distance_covered_m": "prior_game_distance_m",
        "game_max_effort_distance_m": "prior_game_max_effort_distance_m",
        "game_max_effort_runs": "prior_game_max_effort_runs",
        "on_field_total_distance_m": "prior_total_on_field_distance_m",
        "on_field_high_intensity_distance_proxy_m": "prior_high_intensity_proxy_m",
    }
    for source, target in source_map.items():
        if source not in panel.columns:
            panel[source] = np.nan
        values = pd.to_numeric(panel[source], errors="coerce").fillna(0.0)
        prior = values.groupby(key, sort=False).shift(1)
        panel[f"{target}_{lookback_days}d"] = (
            prior.groupby(key, sort=False)
            .transform(lambda s: s.rolling(lookback_days, min_periods=1).sum())
        )

    for source, target in {
        "game_day": "prior_game_days",
        "gps_workload_observed": "prior_measured_practice_days",
        "practice_plan_hit_observed": "prior_plan_hits",
    }.items():
        if source in panel.columns:
            values = pd.to_numeric(panel[source], errors="coerce").fillna(0.0)
        else:
            values = pd.Series(0.0, index=panel.index, dtype=float)
        prior = values.groupby(key, sort=False).shift(1)
        panel[f"{target}_{lookback_days}d"] = (
            prior.groupby(key, sort=False)
            .transform(lambda s: s.rolling(lookback_days, min_periods=1).sum())
        )

    evaluable = (
        panel["practice_plan_evaluable_observed"].fillna(False).astype(bool)
        if "practice_plan_evaluable_observed" in panel.columns
        else pd.Series(False, index=panel.index, dtype=bool)
    )
    hit_observed = (
        panel["practice_plan_hit_observed"].fillna(False).astype(bool)
        if "practice_plan_hit_observed" in panel.columns
        else pd.Series(False, index=panel.index, dtype=bool)
    )
    miss_flag = evaluable & ~hit_observed
    prior_miss = miss_flag.astype(float).groupby(key, sort=False).shift(1)
    panel[f"prior_plan_misses_{lookback_days}d"] = prior_miss.groupby(
        key, sort=False
    ).transform(lambda s: s.rolling(lookback_days, min_periods=1).sum())

    # Direction-specific measured practice-plan misses. These are leakage-safe:
    # each rolling window is shifted one day so the decision date itself is excluded.
    detail = panel.get("practice_plan_result_detail", pd.Series("", index=panel.index)).fillna("").astype(str)
    miss_detail_map = {
        "High below target": "prior_high_below_misses",
        "High above target": "prior_high_above_misses",
        "Moderate below target": "prior_moderate_below_misses",
        "Moderate above target": "prior_moderate_above_misses",
        "Moderate mixed miss": "prior_moderate_mixed_misses",
        "Low above target": "prior_low_above_misses",
    }
    for label, target in miss_detail_map.items():
        values = detail.eq(label).astype(float)
        prior = values.groupby(key, sort=False).shift(1)
        panel[f"{target}_{lookback_days}d"] = prior.groupby(
            key, sort=False
        ).transform(lambda s: s.rolling(lookback_days, min_periods=1).sum())

    state_cols = [
        c
        for c in panel.columns
        if c.endswith(f"_{lookback_days}d") and c.startswith("prior_")
    ]
    join_cols = ["player_key", "date", *state_cols]
    out = decision_df.merge(panel[join_cols], on=["player_key", "date"], how="left")

    out["actual_hsr_m"] = pd.to_numeric(out.get("gps_hsr_distance_m"), errors="coerce")
    out["actual_accelerations"] = pd.to_numeric(out.get("gps_n_accelerations"), errors="coerce")
    out["next_ci_pct_change"] = pd.to_numeric(
        out.get("next_jump_ci_ns_pct_change"), errors="coerce"
    )
    if out["next_ci_pct_change"].isna().all() and "next_jump_ci_ns_pct_change" not in out.columns:
        candidate = "next_jump_ci_ns_pct_change"
        for c in out.columns:
            if c.endswith("next_jump_ci_ns_pct_change") or c == "next_jump_ci_ns_pct_change":
                candidate = c
                break
        if candidate in out.columns:
            out["next_ci_pct_change"] = pd.to_numeric(out[candidate], errors="coerce")

    out["dose_model_eligible"] = (
        out.get("decision_model_eligible", 0).eq(1)
        & out["planned_day_type_3level"].isin(VALID_PLANS)
        & out["actual_hsr_m"].notna()
        & out["actual_accelerations"].notna()
        & out["next_ci_pct_change"].notna()
    ).astype("int8")

    reasons = np.select(
        [
            ~out["planned_day_type_3level"].isin(VALID_PLANS),
            out["actual_hsr_m"].isna() | out["actual_accelerations"].isna(),
            out["next_jump_date"].isna(),
            out["next_ci_pct_change"].isna(),
        ],
        [
            "No scheduled plan",
            "No measured tagged-drill dose",
            "No next jump in outcome window",
            "Next CI change unavailable",
        ],
        default="Eligible",
    )
    out["dose_model_exclusion_reason"] = reasons
    out["dose_lookback_days"] = lookback_days
    return out


def _standardize_frame(frame: pd.DataFrame, columns: list[str]):
    means = frame[columns].mean()
    scales = frame[columns].std(ddof=0).replace(0, 1.0).fillna(1.0)
    return (frame[columns] - means) / scales, means, scales


def _ridge_fit(X: np.ndarray, y: np.ndarray, alpha: float = 1.0):
    Xd = np.column_stack([np.ones(len(X)), X])
    penalty = np.eye(Xd.shape[1]) * alpha
    penalty[0, 0] = 0.0
    beta = np.linalg.pinv(Xd.T @ Xd + penalty) @ Xd.T @ y
    return beta


def _ridge_predict(beta: np.ndarray, X: np.ndarray):
    return np.column_stack([np.ones(len(X)), X]) @ beta


def fit_dynamic_dose_model(
    data: pd.DataFrame,
    scheduled_plan: str,
    lookback_days: int,
    position_group: str | None = None,
    level: str | None = None,
    min_rows: int = 35,
    bootstrap_iterations: int = 150,
    seed: int = 42,
):
    """Fit an interpretable ridge dose-response model with player bootstrap.

    This is an association model, not a causal estimator. It conditions on
    pre-practice state and uses within-player centered dose/state features plus
    player-average terms to reduce between-player confounding.
    """
    model = data.loc[
        data["dose_model_eligible"].eq(1)
        & data["planned_day_type_3level"].eq(scheduled_plan)
    ].copy()
    if position_group and position_group != "All":
        model = model.loc[model["position_group"].eq(position_group)]
    if level and level != "All":
        model = model.loc[model["team"].eq(level)]

    state_cols = [
        f"prior_practice_hsr_m_{lookback_days}d",
        f"prior_practice_accelerations_{lookback_days}d",
        f"prior_game_distance_m_{lookback_days}d",
        f"prior_game_days_{lookback_days}d",
        "jump_ci_ns_last",
        "jump_ci_ns_vs_prev3_test_pct_last",
        "days_since_last_jump",
        "cmj_overall_severity_score_last",
        "cmj_ci_z_last",
        "cmj_mrsi_z_last",
        "cmj_p1_z_last",
        "cmj_cmd_z_last",
        "cmj_ecc_z_last",
        "cmj_bw_total_loss_lb_last",
    ]
    for c in state_cols:
        if c not in model.columns:
            model[c] = np.nan
        model[c] = pd.to_numeric(model[c], errors="coerce")

    model["actual_hsr_m"] = pd.to_numeric(model["actual_hsr_m"], errors="coerce")
    model["actual_accelerations"] = pd.to_numeric(model["actual_accelerations"], errors="coerce")
    model["next_ci_pct_change"] = pd.to_numeric(model["next_ci_pct_change"], errors="coerce")

    # Keep rows with the essential exposure/outcome, then median-impute state.
    model = model.dropna(subset=["actual_hsr_m", "actual_accelerations", "next_ci_pct_change", "player_key"])
    if len(model) < min_rows or model["player_key"].nunique() < 5:
        return None, model, {"reason": "Not enough eligible rows or players."}
    for c in state_cols:
        med = model[c].median()
        model[c] = model[c].fillna(0.0 if pd.isna(med) else med)

    # Winsorize extreme outcomes to prevent a handful of jump changes dominating.
    lo, hi = model["next_ci_pct_change"].quantile([0.01, 0.99])
    model["outcome_model"] = model["next_ci_pct_change"].clip(lo, hi)

    center_cols = ["actual_hsr_m", "actual_accelerations", *state_cols]
    player_means = model.groupby("player_key")[center_cols].transform("mean")
    for c in center_cols:
        model[f"{c}_within"] = model[c] - player_means[c]
        model[f"{c}_between"] = player_means[c]

    feature_cols = [
        "actual_hsr_m_within",
        "actual_accelerations_within",
        f"prior_practice_hsr_m_{lookback_days}d_within",
        f"prior_practice_accelerations_{lookback_days}d_within",
        f"prior_game_distance_m_{lookback_days}d_within",
        "jump_ci_ns_vs_prev3_test_pct_last_within",
        "days_since_last_jump_within",
        "actual_hsr_m_between",
        "actual_accelerations_between",
        f"prior_practice_hsr_m_{lookback_days}d_between",
        f"prior_game_distance_m_{lookback_days}d_between",
        "jump_ci_ns_vs_prev3_test_pct_last_between",
        "cmj_overall_severity_score_last_within",
        "cmj_overall_severity_score_last_between",
        "cmj_ci_z_last_within",
        "cmj_mrsi_z_last_within",
    ]
    # Dose curvature and state-dependent effects.
    model["actual_hsr_sq"] = model["actual_hsr_m_within"] ** 2
    model["actual_accels_sq"] = model["actual_accelerations_within"] ** 2
    model["hsr_x_prior_hsr"] = (
        model["actual_hsr_m_within"]
        * model[f"prior_practice_hsr_m_{lookback_days}d_within"]
    )
    model["accels_x_prior_accels"] = (
        model["actual_accelerations_within"]
        * model[f"prior_practice_accelerations_{lookback_days}d_within"]
    )
    model["hsr_x_game"] = (
        model["actual_hsr_m_within"]
        * model[f"prior_game_distance_m_{lookback_days}d_within"]
    )
    feature_cols += ["actual_hsr_sq", "actual_accels_sq", "hsr_x_prior_hsr", "accels_x_prior_accels", "hsr_x_game"]

    Xz, means, scales = _standardize_frame(model, feature_cols)
    y = model["outcome_model"].to_numpy(float)
    beta = _ridge_fit(Xz.to_numpy(float), y, alpha=2.0)
    fitted = _ridge_predict(beta, Xz.to_numpy(float))
    residual_sd = float(np.nanstd(y - fitted, ddof=max(1, len(beta))))

    rng = np.random.default_rng(seed)
    players = model["player_key"].dropna().unique()
    boot_betas = []
    for _ in range(bootstrap_iterations):
        sampled = rng.choice(players, size=len(players), replace=True)
        pieces = []
        for i, p in enumerate(sampled):
            piece = model.loc[model["player_key"].eq(p)].copy()
            piece["_boot_player"] = f"{p}_{i}"
            pieces.append(piece)
        boot = pd.concat(pieces, ignore_index=True)
        try:
            Xb = (boot[feature_cols] - means) / scales
            boot_betas.append(_ridge_fit(Xb.to_numpy(float), boot["outcome_model"].to_numpy(float), alpha=2.0))
        except Exception:
            continue

    artifact = {
        "beta": beta,
        "boot_betas": np.asarray(boot_betas),
        "means": means,
        "scales": scales,
        "feature_cols": feature_cols,
        "state_cols": state_cols,
        "residual_sd": residual_sd,
        "lookback_days": lookback_days,
        "scheduled_plan": scheduled_plan,
        "n": len(model),
        "players": model["player_key"].nunique(),
    }
    return artifact, model, {}


def predict_dose_grid(
    artifact: dict,
    model_data: pd.DataFrame,
    current_state: dict,
    hsr_values: np.ndarray,
    accel_values: np.ndarray,
):
    """Predict CI response over an HSR x acceleration grid with support counts."""
    rows = []
    lb = artifact["lookback_days"]
    # Use a representative player mean so predictions focus on within-player dose effects.
    between_defaults = {
        c: float(model_data[c].mean())
        for c in model_data.columns
        if c.endswith("_between")
    }
    observed_hsr = model_data["actual_hsr_m"].to_numpy(float)
    observed_acc = model_data["actual_accelerations"].to_numpy(float)
    hsr_tol = max(float(np.nanstd(observed_hsr)) * 0.30, 15.0)
    acc_tol = max(float(np.nanstd(observed_acc)) * 0.30, 4.0)

    for hsr in hsr_values:
        for acc in accel_values:
            rec = {c: 0.0 for c in artifact["feature_cols"]}
            # Current state values are expressed relative to representative player means.
            hsr_between = between_defaults.get("actual_hsr_m_between", float(model_data["actual_hsr_m"].mean()))
            acc_between = between_defaults.get("actual_accelerations_between", float(model_data["actual_accelerations"].mean()))
            rec["actual_hsr_m_within"] = hsr - hsr_between
            rec["actual_accelerations_within"] = acc - acc_between
            rec["actual_hsr_m_between"] = hsr_between
            rec["actual_accelerations_between"] = acc_between

            mappings = {
                f"prior_practice_hsr_m_{lb}d": f"prior_practice_hsr_m_{lb}d",
                f"prior_practice_accelerations_{lb}d": f"prior_practice_accelerations_{lb}d",
                f"prior_game_distance_m_{lb}d": f"prior_game_distance_m_{lb}d",
                "jump_ci_ns_vs_prev3_test_pct_last": "jump_ci_ns_vs_prev3_test_pct_last",
                "days_since_last_jump": "days_since_last_jump",
                "cmj_overall_severity_score_last": "cmj_overall_severity_score_last",
                "cmj_ci_z_last": "cmj_ci_z_last",
                "cmj_mrsi_z_last": "cmj_mrsi_z_last",
            }
            for base, state_key in mappings.items():
                fallback_val = _finite_float(model_data[base].median(), _finite_float(model_data[base].mean(), 0.0))
                val = _finite_float(current_state.get(state_key, fallback_val), fallback_val)
                between_name = f"{base}_between"
                within_name = f"{base}_within"
                b = _finite_float(between_defaults.get(between_name, model_data[base].mean()), fallback_val)
                if within_name in rec:
                    rec[within_name] = val - b
                if between_name in rec:
                    rec[between_name] = b

            rec["actual_hsr_sq"] = rec["actual_hsr_m_within"] ** 2
            rec["actual_accels_sq"] = rec["actual_accelerations_within"] ** 2
            rec["hsr_x_prior_hsr"] = rec["actual_hsr_m_within"] * rec.get(f"prior_practice_hsr_m_{lb}d_within", 0.0)
            rec["accels_x_prior_accels"] = rec["actual_accelerations_within"] * rec.get(f"prior_practice_accelerations_{lb}d_within", 0.0)
            rec["hsr_x_game"] = rec["actual_hsr_m_within"] * rec.get(f"prior_game_distance_m_{lb}d_within", 0.0)

            x = pd.DataFrame([rec])[artifact["feature_cols"]].apply(pd.to_numeric, errors="coerce")
            # Fall back to the training mean for any state that is not yet established
            # (for example a CMJ z-score before six prior sessions).
            x = x.replace([np.inf, -np.inf], np.nan).fillna(artifact["means"])
            xz = ((x - artifact["means"]) / artifact["scales"]).to_numpy(float)
            pred = float(_ridge_predict(artifact["beta"], xz)[0])
            if artifact["boot_betas"].size:
                bp = np.asarray([_ridge_predict(b, xz)[0] for b in artifact["boot_betas"]])
                lower, upper = np.nanquantile(bp, [0.025, 0.975])
            else:
                lower, upper = pred - 1.96 * artifact["residual_sd"], pred + 1.96 * artifact["residual_sd"]

            support = int(np.sum((np.abs(observed_hsr - hsr) <= hsr_tol) & (np.abs(observed_acc - acc) <= acc_tol)))
            if support >= 25:
                support_label = "Strong"
            elif support >= 12:
                support_label = "Moderate"
            elif support >= 5:
                support_label = "Weak"
            else:
                support_label = "Unsupported"
            rows.append({
                "HSR target (m)": float(hsr),
                "Acceleration target": float(acc),
                "Expected next CI change (%)": pred,
                "Lower 95%": float(lower),
                "Upper 95%": float(upper),
                "Historical support n": support,
                "Support": support_label,
            })
    return pd.DataFrame(rows)

def create_decision_outcome_table(df: pd.DataFrame, min_days: int = 2, max_days: int = 7) -> pd.DataFrame:
    """Create one row per planned player-day and attach the next jump 2-7 days later."""
    work = df.sort_values(["player_key", "date"]).copy()
    decisions = work.loc[work["planned_day_type_3level"].isin(VALID_PLANS)].copy()
    jump_metrics = [
        "jump_ci_ns", "jump_mrsi", "jump_peak_power_rel_w_kg", "jump_f0_n"
    ]
    out_parts = []
    for player, d in decisions.groupby("player_key", sort=False):
        all_p = work.loc[work["player_key"].eq(player)].sort_values("date")
        jumps = all_p.loc[all_p.get("jump_observed", 0).eq(1), ["date", *[c for c in jump_metrics if c in all_p.columns]]].copy()
        if jumps.empty:
            d["next_jump_date"] = pd.NaT
            out_parts.append(d)
            continue
        jdates = jumps["date"].to_numpy(dtype="datetime64[ns]")
        next_dates=[]; next_rows=[]
        for dt in d["date"]:
            idx = np.searchsorted(jdates, np.datetime64(dt + pd.Timedelta(days=min_days)), side="left")
            if idx < len(jdates) and pd.Timestamp(jdates[idx]) <= dt + pd.Timedelta(days=max_days):
                next_dates.append(pd.Timestamp(jdates[idx]))
                next_rows.append(jumps.iloc[idx])
            else:
                next_dates.append(pd.NaT); next_rows.append(None)
        d = d.copy(); d["next_jump_date"] = next_dates
        d["days_to_next_jump"] = (d["next_jump_date"] - d["date"]).dt.days
        for metric in jump_metrics:
            if metric not in work.columns: continue
            d[f"next_{metric}"] = [np.nan if r is None else r.get(metric, np.nan) for r in next_rows]
            baseline_col = f"{metric}_last"
            if baseline_col in d.columns:
                base = pd.to_numeric(d[baseline_col], errors="coerce")
                nxt = pd.to_numeric(d[f"next_{metric}"], errors="coerce")
                d[f"next_{metric}_pct_change"] = np.where(base.ne(0), (nxt-base)/base*100.0, np.nan)
        out_parts.append(d)
    out = pd.concat(out_parts, ignore_index=True) if out_parts else decisions.iloc[0:0].copy()
    out["decision_model_eligible"] = (
        out["next_jump_date"].notna()
        & out.get("within_observed_window", 1).eq(1)
        & out.get("jump_ci_ns_last", pd.Series(np.nan, index=out.index)).notna()
    ).astype("int8")
    keep_front = [
        "player_date_id", "date", "player_name", "player_key", "team", "position", "position_group",
        "planned_day_type_3level", "actual_practice_workload_category", "actual_practice_very_high",
        "practice_plan_result", "practice_plan_hit", "practice_plan_hit_observed", "practice_plan_hit_assumed", "practice_plan_miss_type",
        "gps_hsr_distance_m", "gps_n_accelerations", "game_day", "game_distance_covered_m",
        "on_field_total_distance_m", "cmj_overall_status_last", "cmj_overall_severity_score_last",
        "cmj_ci_level_last", "cmj_mrsi_level_last", "cmj_p1_level_last", "cmj_cmd_level_last",
        "cmj_ecc_level_last", "cmj_bw_level_last", "next_jump_date", "days_to_next_jump", "decision_model_eligible",
    ]
    keep_front=[c for c in keep_front if c in out.columns]
    return out[keep_front + [c for c in out.columns if c not in keep_front]]


def create_plan_summary(df: pd.DataFrame) -> pd.DataFrame:
    """Create level/position/day-type compliance summaries.

    Strict compliance uses only measured, tagged-drill practice days.
    Operational compliance additionally allows inferred no-data Low hits when
    that option is enabled. Unmeasured observed plans are not silently counted
    as failures in either denominator.
    """
    x = df.loc[df["planned_day_type_3level"].isin(VALID_PLANS)].copy()

    required_defaults = {
        "practice_plan_evaluable_observed": False,
        "practice_plan_hit_observed": False,
        "practice_plan_evaluable_operational": False,
        "practice_plan_hit_operational": False,
        "practice_plan_hit_assumed": False,
    }
    for col, default in required_defaults.items():
        if col not in x.columns:
            x[col] = default
        x[col] = x[col].fillna(False).astype(bool)

    summary = (
        x.groupby(["team", "position_group", "planned_day_type_3level"], dropna=False)
        .agg(
            planned_days=("player_date_id", "count"),
            measured_days=("practice_plan_evaluable_observed", "sum"),
            observed_hits=("practice_plan_hit_observed", "sum"),
            operational_evaluable_days=("practice_plan_evaluable_operational", "sum"),
            operational_hits=("practice_plan_hit_operational", "sum"),
            assumed_low_hits=("practice_plan_hit_assumed", "sum"),
            median_hsr_m=("gps_hsr_distance_m", "median"),
            median_accelerations=("gps_n_accelerations", "median"),
        )
        .reset_index()
    )

    summary["strict_hit_pct"] = np.where(
        summary["measured_days"].gt(0),
        summary["observed_hits"] / summary["measured_days"] * 100.0,
        np.nan,
    )
    summary["operational_hit_pct"] = np.where(
        summary["operational_evaluable_days"].gt(0),
        summary["operational_hits"] / summary["operational_evaluable_days"] * 100.0,
        np.nan,
    )
    return summary



