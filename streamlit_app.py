def prepare_data(
    raw: pd.DataFrame,
    thresholds: Thresholds,
    include_assumed_no_data_low: bool = True,
    position_thresholds: dict[str, Thresholds] | None = None,
) -> pd.DataFrame:
    """Normalize input and calculate compliance fields."""
    validate_input(raw)
    df = raw.copy()

    df["date"] = pd.to_datetime(df["date"], errors="coerce")
    df = df.loc[df["date"].notna()].copy()

    df["player_name"] = df["player_name"].astype("string").str.strip()
    df["team"] = df["team"].astype("string").str.strip()
    df["position_group"] = (
        df["position_group"].astype("string").str.strip().str.upper()
    )
    df["planned_day_type_3level"] = (
        df["planned_day_type_3level"]
        .astype("string")
        .str.strip()
        .str.title()
        .replace({"Recovery": "Low"})
    )

    # Optionally use a different threshold set for each position group.
    # Any unlisted position falls back to the general thresholds.
    position_thresholds = position_thresholds or {}
    def threshold_for_row(attribute: str) -> pd.Series:
        mapping = {
            position: getattr(position_threshold, attribute)
            for position, position_threshold in position_thresholds.items()
        }
        return df["position_group"].map(mapping).fillna(getattr(thresholds, attribute)).astype(float)

    very_high_hsr_cut = threshold_for_row("very_high_hsr")
    high_hsr_cut = threshold_for_row("high_hsr")
    high_accels_cut = threshold_for_row("high_accels")
    moderate_hsr_min_cut = threshold_for_row("moderate_hsr_min")
    moderate_hsr_max_cut = threshold_for_row("moderate_hsr_max")
    moderate_accels_min_cut = threshold_for_row("moderate_accels_min")
    moderate_accels_max_cut = threshold_for_row("moderate_accels_max_exclusive")
    low_hsr_max_cut = threshold_for_row("low_hsr_max_exclusive")
    low_accels_max_cut = threshold_for_row("low_accels_max_exclusive")

    df["gps_hsr_distance_m"] = safe_numeric(df["gps_hsr_distance_m"])
    df["gps_n_accelerations"] = safe_numeric(df["gps_n_accelerations"])

    # Actual delivered practice exposure. "Very High" is an exposure category,
    # not a planned action parsed from the session name. Planned High days at or above this HSR ceiling are classified as High above
    # target misses and are also flagged as Very High actual workload / High above-target miss for the
    # decision/outcome table.
    actual_category = pd.Series("Unmeasured", index=df.index, dtype="string")
    measured_actual = df["gps_hsr_distance_m"].notna() & df["gps_n_accelerations"].notna()
    very_high_actual = measured_actual & (df["gps_hsr_distance_m"] >= very_high_hsr_cut)
    high_actual = measured_actual & ~very_high_actual & (
        (df["gps_hsr_distance_m"] > high_hsr_cut)
        | (df["gps_n_accelerations"] >= high_accels_cut)
    )
    moderate_actual = measured_actual & ~very_high_actual & ~high_actual & (
        (df["gps_hsr_distance_m"] >= moderate_hsr_min_cut)
        & (df["gps_hsr_distance_m"] <= moderate_hsr_max_cut)
        & (df["gps_n_accelerations"] >= moderate_accels_min_cut)
        & (df["gps_n_accelerations"] < moderate_accels_max_cut)
    )
    low_actual = measured_actual & ~very_high_actual & ~high_actual & ~moderate_actual & (
        (df["gps_hsr_distance_m"] < low_hsr_max_cut)
        & (df["gps_n_accelerations"] < low_accels_max_cut)
    )
    actual_category.loc[very_high_actual] = "Very High"
    actual_category.loc[high_actual] = "High"
    actual_category.loc[moderate_actual] = "Moderate"
    actual_category.loc[low_actual] = "Low"
    actual_category.loc[measured_actual & actual_category.eq("Unmeasured")] = "Between categories"
    df["actual_practice_workload_category"] = actual_category
    df["actual_practice_very_high"] = very_high_actual.astype("int8")

    if "week_start" in df.columns:
        df["week_start"] = pd.to_datetime(df["week_start"], errors="coerce")
    else:
        df["week_start"] = df["date"] - pd.to_timedelta(
            df["date"].dt.weekday, unit="D"
        )

    if "month" not in df.columns:
        df["month"] = df["date"].dt.month
    df["month_label"] = df["date"].dt.to_period("M").astype(str)

    planned_assumed = (
        safe_numeric(
            df.get("planned_day_type_assumed", pd.Series(0, index=df.index)),
            default=0,
        )
        == 1
    )
    planned_observed = (
        safe_numeric(
            df.get("planned_day_type_observed", pd.Series(0, index=df.index)),
            default=0,
        )
        == 1
    )

    # The source dataset can infer Low on days with no practice or game data.
    # This switch lets the user include those inferred days as Low plans or
    # remove them entirely from compliance and jump-response calculations.
    assumed_only = planned_assumed & ~planned_observed
    df["assumed_no_data_low_included"] = assumed_only & include_assumed_no_data_low
    df["assumed_no_data_low_excluded"] = assumed_only & ~include_assumed_no_data_low
    if not include_assumed_no_data_low:
        df.loc[assumed_only, "planned_day_type_3level"] = pd.NA

    df["valid_practice_plan"] = df["planned_day_type_3level"].isin(VALID_PLANS)
    df["tagged_drill_metrics_available"] = (
        df["gps_hsr_distance_m"].notna() & df["gps_n_accelerations"].notna()
    )
    df["practice_plan_evaluable_observed"] = (
        df["valid_practice_plan"] & df["tagged_drill_metrics_available"]
    )

    # Calculate observed compliance.
    hit = pd.Series(False, index=df.index, dtype=bool)

    high_mask = (
        df["practice_plan_evaluable_observed"]
        & df["planned_day_type_3level"].eq("High")
    )
    hit.loc[high_mask] = (
        (df.loc[high_mask, "gps_hsr_distance_m"] < very_high_hsr_cut.loc[high_mask])
        & (
            (df.loc[high_mask, "gps_hsr_distance_m"] > high_hsr_cut.loc[high_mask])
            | (df.loc[high_mask, "gps_n_accelerations"] >= high_accels_cut.loc[high_mask])
        )
    )

    moderate_mask = (
        df["practice_plan_evaluable_observed"]
        & df["planned_day_type_3level"].eq("Moderate")
    )
    hit.loc[moderate_mask] = (
        (
            (df.loc[moderate_mask, "gps_hsr_distance_m"] >= moderate_hsr_min_cut.loc[moderate_mask])
            & (df.loc[moderate_mask, "gps_hsr_distance_m"] <= moderate_hsr_max_cut.loc[moderate_mask])
        )
        & (
            df.loc[moderate_mask, "gps_n_accelerations"]
            >= moderate_accels_min_cut.loc[moderate_mask]
        )
        & (
            df.loc[moderate_mask, "gps_n_accelerations"]
            < moderate_accels_max_cut.loc[moderate_mask]
        )
    )

    low_mask = (
        df["practice_plan_evaluable_observed"]
        & df["planned_day_type_3level"].eq("Low")
    )
    hit.loc[low_mask] = (
        (df.loc[low_mask, "gps_hsr_distance_m"] < low_hsr_max_cut.loc[low_mask])
        & (
            df.loc[low_mask, "gps_n_accelerations"]
            < low_accels_max_cut.loc[low_mask]
        )
    )

    df["practice_plan_hit_observed"] = hit & df["practice_plan_evaluable_observed"]

    # Low days inferred from no practice/game data can be counted operationally,
    # but never as measured compliance.
    df["practice_plan_hit_assumed"] = (
        df["valid_practice_plan"]
        & df["planned_day_type_3level"].eq("Low")
        & planned_assumed
        & ~df["tagged_drill_metrics_available"]
    )
    df["practice_plan_evaluable_operational"] = (
        df["practice_plan_evaluable_observed"] | df["practice_plan_hit_assumed"]
    )
    df["practice_plan_hit_operational"] = (
        df["practice_plan_hit_observed"] | df["practice_plan_hit_assumed"]
    )
    # Backward-compatible alias used by exported decision tables.
    df["practice_plan_hit"] = df["practice_plan_hit_operational"].astype("int8")

    result = pd.Series("Not a practice plan", index=df.index, dtype="string")
    result.loc[df["valid_practice_plan"]] = "Unmeasured"
    result.loc[df["practice_plan_hit_assumed"]] = "Assumed Low hit"
    result.loc[df["practice_plan_hit_observed"]] = "Hit"

    observed_miss = (
        df["practice_plan_evaluable_observed"]
        & ~df["practice_plan_hit_observed"]
    )

    # High can miss in either direction: below its minimum target, or above the
    # Very High HSR ceiling. The upper-bound rule takes precedence.
    high_miss = observed_miss & df["planned_day_type_3level"].eq("High")
    high_too_high = df["gps_hsr_distance_m"] >= very_high_hsr_cut
    result.loc[high_miss & high_too_high] = "Above target"
    result.loc[high_miss & ~high_too_high] = "Below target"

    # Low misses are above the Low ceiling in at least one metric.
    result.loc[observed_miss & df["planned_day_type_3level"].eq("Low")] = (
        "Above target"
    )

    moderate_miss = observed_miss & df["planned_day_type_3level"].eq("Moderate")
    moderate_too_low = (
        (df["gps_hsr_distance_m"] < moderate_hsr_min_cut)
        | (df["gps_n_accelerations"] < moderate_accels_min_cut)
    )
    moderate_too_high = (
        (df["gps_hsr_distance_m"] > moderate_hsr_max_cut)
        | (
            df["gps_n_accelerations"]
            >= moderate_accels_max_cut
        )
    )
    result.loc[moderate_miss & moderate_too_low & moderate_too_high] = "Mixed miss"
    result.loc[moderate_miss & moderate_too_low & ~moderate_too_high] = (
        "Below target"
    )
    result.loc[moderate_miss & moderate_too_high & ~moderate_too_low] = (
        "Above target"
    )

    df["practice_plan_result"] = result

    # Preserve the planned day type in the miss label. This lets the dashboard
    # distinguish a missed High day from an overshot Low day and from the two
    # directions of a missed Moderate day.
    detail = pd.Series("Unmeasured", index=df.index, dtype="string")
    detail.loc[df["practice_plan_hit_observed"]] = (
        df.loc[df["practice_plan_hit_observed"], "planned_day_type_3level"]
        .astype("string") + " hit"
    )
    detail.loc[df["practice_plan_hit_assumed"]] = "Assumed Low hit"
    detail.loc[high_miss & high_too_high] = "High above target"
    detail.loc[high_miss & ~high_too_high] = "High below target"
    detail.loc[
        moderate_miss & moderate_too_low & ~moderate_too_high
    ] = "Moderate below target"
    detail.loc[
        moderate_miss & moderate_too_high & ~moderate_too_low
    ] = "Moderate above target"
    detail.loc[
        moderate_miss & moderate_too_low & moderate_too_high
    ] = "Moderate mixed miss"
    detail.loc[
        observed_miss & df["planned_day_type_3level"].eq("Low")
    ] = "Low above target"
    detail.loc[~df["valid_practice_plan"]] = "No practice plan"
    df["practice_plan_result_detail"] = detail
    df["practice_plan_miss_type"] = detail.where(
        observed_miss,
        pd.NA,
    )

    df["practice_plan_unmeasured"] = (
        df["valid_practice_plan"] & ~df["practice_plan_evaluable_operational"]
    )
    df["planned_day_was_observed"] = planned_observed

    # Per-metric target flags are useful for table exports.
    df["hsr_target_hit"] = pd.Series(pd.NA, index=df.index, dtype="boolean")
    df["acceleration_target_hit"] = pd.Series(
        pd.NA, index=df.index, dtype="boolean"
    )

    df.loc[high_mask, "hsr_target_hit"] = (
        df.loc[high_mask, "gps_hsr_distance_m"] > high_hsr_cut.loc[high_mask]
    )
    df.loc[high_mask, "acceleration_target_hit"] = (
        df.loc[high_mask, "gps_n_accelerations"] >= high_accels_cut.loc[high_mask]
    )
    df.loc[moderate_mask, "hsr_target_hit"] = (
        (
            (df.loc[moderate_mask, "gps_hsr_distance_m"] >= moderate_hsr_min_cut.loc[moderate_mask])
            & (df.loc[moderate_mask, "gps_hsr_distance_m"] <= moderate_hsr_max_cut.loc[moderate_mask])
        )
    )
    df.loc[moderate_mask, "acceleration_target_hit"] = (
        (df.loc[moderate_mask, "gps_n_accelerations"] >= moderate_accels_min_cut.loc[moderate_mask])
        & (
            df.loc[moderate_mask, "gps_n_accelerations"]
            < moderate_accels_max_cut.loc[moderate_mask]
        )
    )
    df.loc[low_mask, "hsr_target_hit"] = (
        df.loc[low_mask, "gps_hsr_distance_m"] < low_hsr_max_cut.loc[low_mask]
    )
    df.loc[low_mask, "acceleration_target_hit"] = (
        df.loc[low_mask, "gps_n_accelerations"]
        < low_accels_max_cut.loc[low_mask]
    )

    # Keep the exact thresholds applied to every row for transparent exports.
    df["applied_very_high_hsr_threshold_m"] = very_high_hsr_cut
    df["applied_high_hsr_threshold_m"] = high_hsr_cut
    df["applied_high_accel_threshold"] = high_accels_cut
    df["applied_moderate_hsr_min_m"] = moderate_hsr_min_cut
    df["applied_moderate_hsr_max_m"] = moderate_hsr_max_cut
    df["applied_moderate_accel_min"] = moderate_accels_min_cut
    df["applied_moderate_accel_max_exclusive"] = moderate_accels_max_cut
    df["applied_low_hsr_max_exclusive_m"] = low_hsr_max_cut
    df["applied_low_accel_max_exclusive"] = low_accels_max_cut

    return df.sort_values(["date", "team", "player_name"]).reset_index(drop=True)


def compliance_summary(df: pd.DataFrame, group_cols: list[str]) -> pd.DataFrame:
    plans = df.loc[df["valid_practice_plan"]].copy()
    if plans.empty:
        columns = group_cols + [
            "planned_days",
            "observed_eligible",
            "observed_hits",
            "strict_hit_pct",
            "assumed_low_hits",
            "operational_eligible",
            "operational_hits",
            "operational_hit_pct",
            "unmeasured_plan_days",
            "below_target",
            "above_target",
            "mixed_miss",
            "high_below_target",
            "high_above_target",
            "moderate_below_target",
            "moderate_above_target",
            "moderate_mixed_miss",
            "low_above_target",
            "median_hsr_m",
            "median_accels",
        ]
        return pd.DataFrame(columns=columns)

    def aggregate(group: pd.DataFrame) -> pd.Series:
        observed_eligible = int(group["practice_plan_evaluable_observed"].sum())
        observed_hits = int(group["practice_plan_hit_observed"].sum())
        assumed_low = int(group["practice_plan_hit_assumed"].sum())
        operational_eligible = int(group["practice_plan_evaluable_operational"].sum())
        operational_hits = int(group["practice_plan_hit_operational"].sum())
        measured = group.loc[group["practice_plan_evaluable_observed"]]
        return pd.Series(
            {
                "planned_days": len(group),
                "observed_eligible": observed_eligible,
                "observed_hits": observed_hits,
                "strict_hit_pct": 100 * safe_rate(observed_hits, observed_eligible),
                "assumed_low_hits": assumed_low,
                "operational_eligible": operational_eligible,
                "operational_hits": operational_hits,
                "operational_hit_pct": 100
                * safe_rate(operational_hits, operational_eligible),
                "unmeasured_plan_days": int(group["practice_plan_unmeasured"].sum()),
                "below_target": int(
                    group["practice_plan_result"].eq("Below target").sum()
                ),
                "above_target": int(
                    group["practice_plan_result"].eq("Above target").sum()
                ),
                "mixed_miss": int(
                    group["practice_plan_result"].eq("Mixed miss").sum()
                ),
                "high_below_target": int(
                    group["practice_plan_result_detail"].eq("High below target").sum()
                ),
                "high_above_target": int(
                    group["practice_plan_result_detail"].eq("High above target").sum()
                ),
                "moderate_below_target": int(
                    group["practice_plan_result_detail"].eq("Moderate below target").sum()
                ),
                "moderate_above_target": int(
                    group["practice_plan_result_detail"].eq("Moderate above target").sum()
                ),
                "moderate_mixed_miss": int(
                    group["practice_plan_result_detail"].eq("Moderate mixed miss").sum()
                ),
                "low_above_target": int(
                    group["practice_plan_result_detail"].eq("Low above target").sum()
                ),
                "median_hsr_m": measured["gps_hsr_distance_m"].median(),
                "median_accels": measured["gps_n_accelerations"].median(),
            }
        )

    if group_cols:
        summary = (
            plans.groupby(group_cols, dropna=False, observed=True)
            .apply(aggregate, include_groups=False)
            .reset_index()
        )
    else:
        summary = aggregate(plans).to_frame().T
    return summary


def percent_text(value: float) -> str:
    return "—" if pd.isna(value) else f"{value:.1f}%"


def format_summary_table(summary: pd.DataFrame) -> pd.DataFrame:
    out = summary.copy()
    percent_columns = [
        "strict_hit_pct",
        "operational_hit_pct",
        "Strict hit %",
        "Operational hit %",
        "Measured coverage %",
        "Assumed Low share %",
    ]
    for col in percent_columns:
        if col in out.columns:
            out[col] = out[col].map(percent_text)
    numeric_display_columns = [
        "median_hsr_m",
        "median_accels",
        "Median HSR",
        "Median accels",
    ]
    for col in numeric_display_columns:
        if col in out.columns:
            out[col] = out[col].map(lambda x: "—" if pd.isna(x) else f"{x:.1f}")
    return out


