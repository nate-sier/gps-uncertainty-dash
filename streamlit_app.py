def _support_label(n: int) -> str:
    if n >= 25:
        return "Strong"
    if n >= 12:
        return "Moderate"
    if n >= 5:
        return "Weak"
    return "Unsupported"


def _support_rank(label: str) -> int:
    return {"Unsupported": 0, "Weak": 1, "Moderate": 2, "Strong": 3}.get(str(label), 0)


def _finite_float(value, fallback=0.0) -> float:
    """Return a finite float, otherwise a finite fallback.

    Streamlit/player-state rows can legitimately contain NaN for CMJ z-scores
    before enough sessions exist. Recommendation scoring must not let those NaNs
    propagate into an entire candidate grid.
    """
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = float(fallback)
    if not np.isfinite(v):
        try:
            v = float(fallback)
        except (TypeError, ValueError):
            v = 0.0
    return v if np.isfinite(v) else 0.0


def candidate_execution_label(plan: str, hsr: float, accels: float, t) -> str:
    """Classify a proposed HSR/acceleration dose using the current dashboard definitions."""
    hsr = float(hsr)
    accels = float(accels)
    if plan == "High":
        if hsr >= float(t.very_high_hsr):
            return "High above target"
        if (hsr > float(t.high_hsr)) or (accels >= float(t.high_accels)):
            return "High hit"
        return "High below target"
    if plan == "Moderate":
        too_low = (hsr < float(t.moderate_hsr_min)) or (accels < float(t.moderate_accels_min))
        too_high = (hsr > float(t.moderate_hsr_max)) or (accels >= float(t.moderate_accels_max_exclusive))
        if too_low and too_high:
            return "Moderate mixed miss"
        if too_low:
            return "Moderate below target"
        if too_high:
            return "Moderate above target"
        return "Moderate hit"
    if plan == "Low":
        if (hsr < float(t.low_hsr_max_exclusive)) and (accels < float(t.low_accels_max_exclusive)):
            return "Low hit"
        return "Low above target"
    return "Unknown"


def latest_recommendation_state(panel: pd.DataFrame, player_key: str, lookback_days: int = 5):
    """Build a leakage-safe next-day state from the latest available player-date.

    The reference date is one calendar day after the player's latest row. Therefore
    the selected lookback window consists entirely of observed days before the
    hypothetical recommendation date.
    """
    p = panel.loc[panel["player_key"].eq(player_key)].sort_values("date").copy()
    if p.empty:
        return None
    p["date"] = pd.to_datetime(p["date"], errors="coerce")
    p = p.dropna(subset=["date"])
    if p.empty:
        return None
    last_date = p["date"].max()
    reference_date = last_date + pd.Timedelta(days=1)
    window_start = reference_date - pd.Timedelta(days=int(lookback_days))
    w = p.loc[(p["date"] >= window_start) & (p["date"] < reference_date)].copy()
    latest = p.iloc[-1]

    def sum_col(col):
        if col not in w.columns:
            return 0.0
        return float(pd.to_numeric(w[col], errors="coerce").fillna(0.0).sum())

    detail = w.get("practice_plan_result_detail", pd.Series("", index=w.index)).fillna("").astype(str)
    state = {
        f"prior_total_on_field_distance_m_{lookback_days}d": sum_col("on_field_total_distance_m"),
        f"prior_high_intensity_proxy_m_{lookback_days}d": sum_col("on_field_high_intensity_distance_proxy_m"),
        f"prior_practice_hsr_m_{lookback_days}d": sum_col("gps_hsr_distance_m"),
        f"prior_practice_accelerations_{lookback_days}d": sum_col("gps_n_accelerations"),
        f"prior_game_distance_m_{lookback_days}d": sum_col("game_distance_covered_m"),
        f"prior_game_max_effort_distance_m_{lookback_days}d": sum_col("game_max_effort_distance_m"),
        f"prior_game_max_effort_runs_{lookback_days}d": sum_col("game_max_effort_runs"),
        f"prior_game_days_{lookback_days}d": sum_col("game_day"),
        f"prior_plan_misses_{lookback_days}d": float(detail.isin([
            "High below target", "High above target", "Moderate below target",
            "Moderate above target", "Moderate mixed miss", "Low above target"
        ]).sum()),
        f"prior_high_below_misses_{lookback_days}d": float(detail.eq("High below target").sum()),
        f"prior_high_above_misses_{lookback_days}d": float(detail.eq("High above target").sum()),
        f"prior_moderate_below_misses_{lookback_days}d": float(detail.eq("Moderate below target").sum()),
        f"prior_moderate_above_misses_{lookback_days}d": float(detail.eq("Moderate above target").sum()),
        f"prior_moderate_mixed_misses_{lookback_days}d": float(detail.eq("Moderate mixed miss").sum()),
        f"prior_low_above_misses_{lookback_days}d": float(detail.eq("Low above target").sum()),
    }

    def latest_num(col, default=np.nan):
        if col not in p.columns:
            return default
        v = pd.to_numeric(pd.Series([latest.get(col, np.nan)]), errors="coerce").iloc[0]
        return default if pd.isna(v) else float(v)

    state.update({
        "jump_ci_ns_last": latest_num("jump_ci_ns_last"),
        "jump_ci_ns_vs_prev3_test_pct_last": latest_num("jump_ci_ns_vs_prev3_test_pct_last", 0.0),
        "cmj_overall_severity_score_last": latest_num("cmj_overall_severity_score_last", 0.0),
        "cmj_ci_z_last": latest_num("cmj_ci_z_last", 0.0),
        "cmj_mrsi_z_last": latest_num("cmj_mrsi_z_last", 0.0),
        "cmj_any_flag_last": latest_num("cmj_any_flag_last", 0.0),
    })

    jumps = p.loc[safe_numeric(p.get("jump_observed", pd.Series(0, index=p.index)), default=0).eq(1), "date"]
    if len(jumps):
        state["days_since_last_jump"] = float((reference_date - jumps.max()).days)
    else:
        state["days_since_last_jump"] = np.nan

    return {
        "state": state,
        "reference_date": reference_date,
        "latest_data_date": last_date,
        "team": latest.get("team", ""),
        "position_group": latest.get("position_group", ""),
        "player_name": latest.get("player_name", str(player_key)),
    }


def fit_recommendation_flag_model(
    audit: pd.DataFrame,
    scheduled_plan: str,
    lookback_days: int,
    position_group: str | None = None,
    level: str | None = None,
    min_rows: int = 60,
    bootstrap_iterations: int = 60,
    seed: int = 2026,
):
    """Fit a new-CMJ-flag onset model that explicitly includes realized dose.

    Only currently-unflagged, flag-eligible historical rows with measured tagged-
    drill HSR and acceleration exposure are used. This keeps assumed Low days from
    being treated as measured evidence for a specific Low dose.
    """
    x = audit.loc[
        audit.get("audit_eligible_flag", 0).eq(1)
        & audit["planned_day_type_3level"].eq(scheduled_plan)
    ].copy()
    if position_group and position_group != "All":
        x = x.loc[x["position_group"].eq(position_group)]
    if level and level != "All":
        x = x.loc[x["team"].eq(level)]

    lb = int(lookback_days)
    base_cols = [
        f"prior_total_on_field_distance_m_{lb}d",
        f"prior_high_intensity_proxy_m_{lb}d",
        f"prior_practice_hsr_m_{lb}d",
        f"prior_practice_accelerations_{lb}d",
        f"prior_game_distance_m_{lb}d",
        f"prior_game_max_effort_distance_m_{lb}d",
        f"prior_game_max_effort_runs_{lb}d",
        f"prior_game_days_{lb}d",
        f"prior_plan_misses_{lb}d",
        f"prior_high_below_misses_{lb}d",
        f"prior_high_above_misses_{lb}d",
        f"prior_moderate_below_misses_{lb}d",
        f"prior_moderate_above_misses_{lb}d",
        f"prior_moderate_mixed_misses_{lb}d",
        f"prior_low_above_misses_{lb}d",
        "jump_ci_ns_vs_prev3_test_pct_last",
        "days_since_last_jump",
        "cmj_ci_z_last",
        "cmj_mrsi_z_last",
        "actual_hsr_m",
        "actual_accelerations",
    ]
    for c in base_cols:
        if c not in x.columns:
            x[c] = np.nan
        x[c] = pd.to_numeric(x[c], errors="coerce")
    x["target"] = pd.to_numeric(x.get("next_cmj_new_flag_onset"), errors="coerce")
    x = x.dropna(subset=["target", "actual_hsr_m", "actual_accelerations", "player_key"])
    if len(x) < min_rows or x["player_key"].nunique() < 5 or x["target"].nunique() < 2:
        return None, x, {"reason": "Not enough measured unflagged rows, players, or flag outcomes."}

    prior_hi = f"prior_high_intensity_proxy_m_{lb}d"
    prior_acc = f"prior_practice_accelerations_{lb}d"
    x["actual_hsr_sq"] = x["actual_hsr_m"] ** 2
    x["actual_accels_sq"] = x["actual_accelerations"] ** 2
    x["actual_hsr_x_prior_high_intensity"] = x["actual_hsr_m"].fillna(0) * x[prior_hi].fillna(0)
    x["actual_accels_x_prior_accels"] = x["actual_accelerations"].fillna(0) * x[prior_acc].fillna(0)
    x["actual_hsr_x_ci_z"] = x["actual_hsr_m"].fillna(0) * x["cmj_ci_z_last"].fillna(0)
    feature_cols = base_cols + [
        "actual_hsr_sq",
        "actual_accels_sq",
        "actual_hsr_x_prior_high_intensity",
        "actual_accels_x_prior_accels",
        "actual_hsr_x_ci_z",
    ]

    medians = x[feature_cols].median().fillna(0.0)
    filled = x[feature_cols].fillna(medians)
    means = filled.mean()
    scales = filled.std(ddof=0).replace(0, 1.0).fillna(1.0)
    X = ((filled - means) / scales).to_numpy(float)
    y = x["target"].to_numpy(float)
    beta = _audit_logistic_fit(X, y, ridge=2.0)

    rng = np.random.default_rng(seed)
    players = x["player_key"].dropna().unique()
    boot_betas = []
    for _ in range(int(bootstrap_iterations)):
        sampled = rng.choice(players, size=len(players), replace=True)
        pieces = [x.loc[x["player_key"].eq(p)] for p in sampled]
        if not pieces:
            continue
        b = pd.concat(pieces, ignore_index=True)
        if b["target"].nunique() < 2:
            continue
        try:
            Xb = ((b[feature_cols].fillna(medians) - means) / scales).to_numpy(float)
            boot_betas.append(_audit_logistic_fit(Xb, b["target"].to_numpy(float), ridge=2.0))
        except Exception:
            continue

    artifact = {
        "beta": beta,
        "boot_betas": np.asarray(boot_betas),
        "medians": medians,
        "means": means,
        "scales": scales,
        "feature_cols": feature_cols,
        "lookback_days": lb,
        "scheduled_plan": scheduled_plan,
        "n": len(x),
        "players": x["player_key"].nunique(),
    }
    return artifact, x, {}


def predict_flag_risk_grid(artifact: dict, model_data: pd.DataFrame, current_state: dict, candidate_grid: pd.DataFrame):
    lb = int(artifact["lookback_days"])
    observed_hsr = pd.to_numeric(model_data["actual_hsr_m"], errors="coerce").to_numpy(float)
    observed_acc = pd.to_numeric(model_data["actual_accelerations"], errors="coerce").to_numpy(float)
    hsr_tol = max(float(np.nanstd(observed_hsr)) * 0.30, 15.0)
    acc_tol = max(float(np.nanstd(observed_acc)) * 0.30, 4.0)
    rows = []
    for _, cand in candidate_grid.iterrows():
        hsr = float(cand["HSR target (m)"])
        acc = float(cand["Acceleration target"])
        rec = {}
        for c in artifact["feature_cols"]:
            if c in {"actual_hsr_m", "actual_accelerations", "actual_hsr_sq", "actual_accels_sq",
                     "actual_hsr_x_prior_high_intensity", "actual_accels_x_prior_accels", "actual_hsr_x_ci_z"}:
                continue
            rec[c] = current_state.get(c, artifact["medians"].get(c, 0.0))
        rec["actual_hsr_m"] = hsr
        rec["actual_accelerations"] = acc
        rec["actual_hsr_sq"] = hsr ** 2
        rec["actual_accels_sq"] = acc ** 2
        rec["actual_hsr_x_prior_high_intensity"] = hsr * _finite_float(current_state.get(f"prior_high_intensity_proxy_m_{lb}d", 0.0), 0.0)
        rec["actual_accels_x_prior_accels"] = acc * _finite_float(current_state.get(f"prior_practice_accelerations_{lb}d", 0.0), 0.0)
        rec["actual_hsr_x_ci_z"] = hsr * _finite_float(current_state.get("cmj_ci_z_last", 0.0), 0.0)
        x = pd.DataFrame([rec])[artifact["feature_cols"]]
        xz = ((x.fillna(artifact["medians"]) - artifact["means"]) / artifact["scales"]).to_numpy(float)
        pred = float(_audit_logistic_predict(artifact["beta"], xz)[0])
        if artifact["boot_betas"].size:
            bp = np.asarray([_audit_logistic_predict(b, xz)[0] for b in artifact["boot_betas"]], dtype=float).reshape(-1)
            lower, upper = np.nanquantile(bp, [0.025, 0.975])
        else:
            lower, upper = np.nan, np.nan
        support = int(np.sum((np.abs(observed_hsr - hsr) <= hsr_tol) & (np.abs(observed_acc - acc) <= acc_tol)))
        rows.append({
            "HSR target (m)": hsr,
            "Acceleration target": acc,
            "Predicted new-flag risk %": 100.0 * pred,
            "Flag risk lower 95%": 100.0 * float(lower) if np.isfinite(lower) else np.nan,
            "Flag risk upper 95%": 100.0 * float(upper) if np.isfinite(upper) else np.nan,
            "Flag historical support n": support,
            "Flag support": _support_label(support),
        })
    return pd.DataFrame(rows)

def decision_overlap_summary(audit: pd.DataFrame, lookback_days: int = 5) -> pd.DataFrame:
    """Show historical representation of each plan across coarse pre-practice states."""
    x = audit.loc[audit.get("decision_model_eligible", 0).eq(1)].copy()
    if x.empty:
        return pd.DataFrame()
    workload_col = f"prior_high_intensity_proxy_m_{lookback_days}d"
    if workload_col not in x.columns:
        workload_col = f"prior_practice_hsr_m_{lookback_days}d"
    x[workload_col] = pd.to_numeric(x.get(workload_col), errors="coerce")
    x["cmj_state"] = x.get("cmj_overall_status_last", "").fillna("").astype(str).replace({"": "None"})
    x["workload_state"] = "Unknown"
    valid = x[workload_col].notna()
    if valid.sum() >= 8:
        try:
            q = x.loc[valid, workload_col].quantile([0.25,0.5,0.75]).to_numpy(float)
            x.loc[valid, "workload_state"] = pd.cut(
                x.loc[valid, workload_col],
                bins=[-np.inf, q[0], q[1], q[2], np.inf],
                labels=["Q1", "Q2", "Q3", "Q4"],
                include_lowest=True,
            ).astype(str)
        except Exception:
            pass
    grp = x.groupby(["position_group", "workload_state", "cmj_state", "planned_day_type_3level"], observed=True).size().rename("N").reset_index()
    totals = grp.groupby(["position_group", "workload_state", "cmj_state"], observed=True)["N"].transform("sum")
    grp["Historical plan share %"] = np.where(totals.gt(0), grp["N"] / totals * 100.0, np.nan)
    return grp.sort_values(["position_group", "workload_state", "cmj_state", "planned_day_type_3level"])

