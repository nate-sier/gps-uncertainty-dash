def _audit_auc(y_true: np.ndarray, scores: np.ndarray) -> float:
    y = np.asarray(y_true, dtype=float)
    s = np.asarray(scores, dtype=float)
    mask = np.isfinite(y) & np.isfinite(s)
    y, s = y[mask], s[mask]
    pos = s[y == 1]
    neg = s[y == 0]
    if len(pos) == 0 or len(neg) == 0:
        return np.nan
    # Mann-Whitney formulation of AUROC, with half-credit for ties.
    wins = 0.0
    for p in pos:
        wins += np.sum(p > neg) + 0.5 * np.sum(p == neg)
    return float(wins / (len(pos) * len(neg)))


def _audit_logistic_fit(X: np.ndarray, y: np.ndarray, ridge: float = 1.0, max_iter: int = 80):
    X = np.asarray(X, dtype=float)
    y = np.asarray(y, dtype=float)
    Xd = np.column_stack([np.ones(len(X)), X])
    beta = np.zeros(Xd.shape[1], dtype=float)
    penalty = np.eye(Xd.shape[1]) * ridge
    penalty[0, 0] = 0.0
    for _ in range(max_iter):
        eta = np.clip(Xd @ beta, -30, 30)
        p = 1.0 / (1.0 + np.exp(-eta))
        w = np.clip(p * (1.0 - p), 1e-6, None)
        z = eta + (y - p) / w
        XtW = Xd.T * w
        beta_new = np.linalg.pinv(XtW @ Xd + penalty) @ (XtW @ z)
        if np.max(np.abs(beta_new - beta)) < 1e-7:
            beta = beta_new
            break
        beta = beta_new
    return beta


def _audit_logistic_predict(beta: np.ndarray, X: np.ndarray) -> np.ndarray:
    Xd = np.column_stack([np.ones(len(X)), np.asarray(X, dtype=float)])
    eta = np.clip(Xd @ beta, -30, 30)
    return 1.0 / (1.0 + np.exp(-eta))


def add_next_flag_outcome(decision_table: pd.DataFrame, panel: pd.DataFrame) -> pd.DataFrame:
    """Attach flag status of the next CMJ test already selected in the decision table."""
    out = decision_table.copy()
    jumps = panel.loc[
        safe_numeric(panel.get("jump_observed", pd.Series(0, index=panel.index)), default=0).eq(1)
    ].copy()
    if jumps.empty or "next_jump_date" not in out.columns:
        out["next_cmj_any_flag"] = np.nan
        out["next_cmj_review_flag"] = np.nan
        out["next_cmj_new_flag_onset"] = np.nan
        return out

    for col in ["cmj_any_flag", "cmj_review_flag"]:
        if col not in jumps.columns:
            jumps[col] = 0
        jumps[col] = safe_numeric(jumps[col], default=0)
    jumps = jumps.sort_values(["player_key", "date"])
    jumps["previous_cmj_any_flag"] = jumps.groupby("player_key")["cmj_any_flag"].shift(1).fillna(0)
    jumps["cmj_new_flag_onset"] = (
        jumps["cmj_any_flag"].eq(1) & jumps["previous_cmj_any_flag"].eq(0)
    ).astype(int)
    lookup = jumps[[
        "player_key", "date", "cmj_any_flag", "cmj_review_flag", "cmj_new_flag_onset"
    ]].rename(columns={
        "date": "next_jump_date",
        "cmj_any_flag": "next_cmj_any_flag",
        "cmj_review_flag": "next_cmj_review_flag",
        "cmj_new_flag_onset": "next_cmj_new_flag_onset",
    })
    out = out.merge(lookup, on=["player_key", "next_jump_date"], how="left")
    return out


def build_model_audit_dataset(
    panel: pd.DataFrame,
    decision_table: pd.DataFrame,
    lookback_days: int = 5,
) -> pd.DataFrame:
    """Create leakage-safe model-audit rows with next-CMJ flag outcomes."""
    audit = build_dose_response_table(panel, decision_table, lookback_days=lookback_days)
    audit = add_next_flag_outcome(audit, panel)
    audit["audit_eligible_ci"] = audit.get("dose_model_eligible", 0).eq(1).astype(int)

    planned_assumed = pd.to_numeric(
        audit.get("planned_day_type_assumed", pd.Series(0, index=audit.index)),
        errors="coerce",
    ).fillna(0).eq(1)
    audit["planned_low_assumed"] = (
        audit["planned_day_type_3level"].eq("Low") & planned_assumed
    ).astype(int)
    audit["planned_low_observed"] = (
        audit["planned_day_type_3level"].eq("Low") & ~planned_assumed
    ).astype(int)
    audit["low_measurement_source"] = np.select(
        [audit["planned_low_assumed"].eq(1), audit["planned_low_observed"].eq(1)],
        ["Assumed Low (no data)", "Observed Low"],
        default="Not Low",
    )

    # A true *new* flag onset can only occur when the latest known CMJ state
    # before the decision is unflagged. Existing flagged states are retained in
    # the audit table but excluded from onset-model training rather than being
    # incorrectly coded as negative onsets.
    current_flag = pd.to_numeric(
        audit.get("cmj_any_flag_last", pd.Series(np.nan, index=audit.index)),
        errors="coerce",
    )
    if current_flag.isna().all():
        current_flag = pd.to_numeric(
            audit.get("cmj_overall_severity_score_last", pd.Series(np.nan, index=audit.index)),
            errors="coerce",
        ).fillna(0).gt(0).astype(float)
    audit["predecision_cmj_flagged"] = current_flag.fillna(0).gt(0).astype(int)

    audit["audit_eligible_flag"] = (
        audit.get("decision_model_eligible", 0).eq(1)
        & audit["planned_day_type_3level"].isin(VALID_PLANS)
        & audit["next_cmj_new_flag_onset"].notna()
        & audit["predecision_cmj_flagged"].eq(0)
    ).astype(int)
    return audit


def chronological_flag_risk_audit(audit: pd.DataFrame, lookback_days: int = 5):
    """Prospectively validate new-CMJ-flag onset risk and return standardized effects.

    The model is trained through June, validated in July, and tested in August+.
    Assumed Low days are retained but explicitly identified so they cannot be
    silently treated as equivalent to measured Low sessions.
    """
    x = audit.loc[audit["audit_eligible_flag"].eq(1)].copy()
    if x.empty:
        return pd.DataFrame(), pd.DataFrame(), pd.DataFrame()

    base_cols = [
        f"prior_total_on_field_distance_m_{lookback_days}d",
        f"prior_high_intensity_proxy_m_{lookback_days}d",
        f"prior_practice_hsr_m_{lookback_days}d",
        f"prior_practice_accelerations_{lookback_days}d",
        f"prior_game_distance_m_{lookback_days}d",
        f"prior_game_max_effort_distance_m_{lookback_days}d",
        f"prior_game_max_effort_runs_{lookback_days}d",
        f"prior_game_days_{lookback_days}d",
        f"prior_plan_misses_{lookback_days}d",
        f"prior_high_below_misses_{lookback_days}d",
        f"prior_high_above_misses_{lookback_days}d",
        f"prior_moderate_below_misses_{lookback_days}d",
        f"prior_moderate_above_misses_{lookback_days}d",
        f"prior_moderate_mixed_misses_{lookback_days}d",
        f"prior_low_above_misses_{lookback_days}d",
        "jump_ci_ns_vs_prev3_test_pct_last",
        "days_since_last_jump",
        "cmj_ci_z_last",
        "cmj_mrsi_z_last",
        "planned_low_assumed",
    ]
    for c in base_cols:
        if c not in x.columns:
            x[c] = np.nan
        x[c] = pd.to_numeric(x[c], errors="coerce")

    # Encode planned action explicitly. Moderate is the reference category.
    x["planned_high"] = x["planned_day_type_3level"].eq("High").astype(float)
    x["planned_low"] = x["planned_day_type_3level"].eq("Low").astype(float)

    # Interactions that directly represent the planning-under-uncertainty questions.
    hi_col = f"prior_high_intensity_proxy_m_{lookback_days}d"
    if hi_col not in x.columns or x[hi_col].isna().all():
        hi_col = f"prior_practice_hsr_m_{lookback_days}d"
    x["planned_high_x_prior_high_intensity"] = x["planned_high"] * x[hi_col].fillna(0)
    x["planned_low_x_prior_high_intensity"] = x["planned_low"] * x[hi_col].fillna(0)
    x["high_above_x_prior_high_intensity"] = x[f"prior_high_above_misses_{lookback_days}d"].fillna(0) * x[hi_col].fillna(0)
    x["high_below_x_prior_high_intensity"] = x[f"prior_high_below_misses_{lookback_days}d"].fillna(0) * x[hi_col].fillna(0)
    x["low_above_x_prior_high_intensity"] = x[f"prior_low_above_misses_{lookback_days}d"].fillna(0) * x[hi_col].fillna(0)

    feature_cols = base_cols + [
        "planned_high",
        "planned_low",
        "planned_high_x_prior_high_intensity",
        "planned_low_x_prior_high_intensity",
        "high_above_x_prior_high_intensity",
        "high_below_x_prior_high_intensity",
        "low_above_x_prior_high_intensity",
    ]
    x["date"] = pd.to_datetime(x["date"], errors="coerce")
    x["target"] = pd.to_numeric(x["next_cmj_new_flag_onset"], errors="coerce")
    x = x.dropna(subset=["date", "target"])
    if x.empty:
        return pd.DataFrame(), pd.DataFrame(), pd.DataFrame()

    train = x.loc[x["date"] <= pd.Timestamp("2026-06-30")].copy()
    valid = x.loc[x["date"].between(pd.Timestamp("2026-07-01"), pd.Timestamp("2026-07-31"))].copy()
    test = x.loc[x["date"] >= pd.Timestamp("2026-08-01")].copy()
    if len(train) < 40 or train["target"].nunique() < 2:
        return pd.DataFrame(), pd.DataFrame(), pd.DataFrame()

    medians = train[feature_cols].median().fillna(0.0)
    means = train[feature_cols].fillna(medians).mean()
    scales = train[feature_cols].fillna(medians).std(ddof=0).replace(0, 1.0).fillna(1.0)

    def matrix(frame):
        return ((frame[feature_cols].fillna(medians) - means) / scales).to_numpy(float)

    beta = _audit_logistic_fit(matrix(train), train["target"].to_numpy(float), ridge=2.0)

    effect_rows = []
    pretty = {
        f"prior_total_on_field_distance_m_{lookback_days}d": "Prior combined practice + game distance",
        f"prior_high_intensity_proxy_m_{lookback_days}d": "Prior high-intensity distance proxy",
        f"prior_practice_hsr_m_{lookback_days}d": "Prior practice HSR",
        f"prior_practice_accelerations_{lookback_days}d": "Prior practice accelerations",
        f"prior_game_distance_m_{lookback_days}d": "Prior game distance",
        f"prior_game_max_effort_distance_m_{lookback_days}d": "Prior game max-effort distance",
        f"prior_game_max_effort_runs_{lookback_days}d": "Prior game max-effort runs",
        f"prior_game_days_{lookback_days}d": "Game days in window",
        f"prior_plan_misses_{lookback_days}d": "Measured plan misses",
        f"prior_high_below_misses_{lookback_days}d": "High-below misses",
        f"prior_high_above_misses_{lookback_days}d": "High-above misses",
        f"prior_moderate_below_misses_{lookback_days}d": "Moderate-below misses",
        f"prior_moderate_above_misses_{lookback_days}d": "Moderate-above misses",
        f"prior_moderate_mixed_misses_{lookback_days}d": "Moderate mixed misses",
        f"prior_low_above_misses_{lookback_days}d": "Low-above misses",
        "jump_ci_ns_vs_prev3_test_pct_last": "Latest CI vs previous 3 tests",
        "days_since_last_jump": "Days since last CMJ",
        "cmj_ci_z_last": "Latest CI z-score",
        "cmj_mrsi_z_last": "Latest mRSI z-score",
        "planned_low_assumed": "Assumed Low (no measured Low session)",
        "planned_high": "Planned High vs Moderate",
        "planned_low": "Planned Low vs Moderate",
        "planned_high_x_prior_high_intensity": "Planned High × prior high-intensity load",
        "planned_low_x_prior_high_intensity": "Planned Low × prior high-intensity load",
        "high_above_x_prior_high_intensity": "High-above miss × prior high-intensity load",
        "high_below_x_prior_high_intensity": "High-below miss × prior high-intensity load",
        "low_above_x_prior_high_intensity": "Low-above miss × prior high-intensity load",
    }
    for i, col in enumerate(feature_cols, start=1):
        b = float(beta[i])
        effect_rows.append({
            "Predictor": pretty.get(col, col),
            "Standardized coefficient": b,
            "Odds ratio per 1 SD": float(np.exp(np.clip(b, -10, 10))),
            "Direction": "Higher flag risk" if b > 0 else ("Lower flag risk" if b < 0 else "Neutral"),
        })
    effects = pd.DataFrame(effect_rows).sort_values("Standardized coefficient", key=lambda z: z.abs(), ascending=False)

    metric_rows = []
    scored_parts = []
    for name, frame in [("Train (Apr-Jun)", train), ("Validation (Jul)", valid), ("Test (Aug+)", test)]:
        if frame.empty:
            continue
        pred = _audit_logistic_predict(beta, matrix(frame))
        obs = frame["target"].to_numpy(float)
        scored_cols = ["player_key", "player_name", "date", "team", "position_group", "planned_day_type_3level", "low_measurement_source", "target"]
        scored = frame[[c for c in scored_cols if c in frame.columns]].copy()
        scored["predicted_new_flag_risk"] = pred
        scored["split"] = name
        scored_parts.append(scored)
        # threshold metrics at 0.50 are included only as an audit reference; risk
        # calibration and AUROC remain the primary criteria for this imbalanced outcome.
        cls = pred >= 0.50
        tp = int(np.sum((cls == 1) & (obs == 1)))
        tn = int(np.sum((cls == 0) & (obs == 0)))
        fp = int(np.sum((cls == 1) & (obs == 0)))
        fn = int(np.sum((cls == 0) & (obs == 1)))
        sensitivity = tp / (tp + fn) if (tp + fn) else np.nan
        specificity = tn / (tn + fp) if (tn + fp) else np.nan
        metric_rows.append({
            "Split": name,
            "Rows": len(frame),
            "Players": frame["player_key"].nunique(),
            "New flag rate %": 100 * float(np.mean(obs)) if len(obs) else np.nan,
            "AUROC": _audit_auc(obs, pred),
            "Brier score": float(np.mean((pred - obs) ** 2)),
            "Mean predicted risk %": 100 * float(np.mean(pred)),
            "Sensitivity @ 0.50 %": 100 * sensitivity if np.isfinite(sensitivity) else np.nan,
            "Specificity @ 0.50 %": 100 * specificity if np.isfinite(specificity) else np.nan,
        })
    return (
        pd.DataFrame(metric_rows),
        (pd.concat(scored_parts, ignore_index=True) if scored_parts else pd.DataFrame()),
        effects,
    )


