def infer_team(x):
    """Parse roster/affiliate from the STATSports session name.

    GPS session naming is the source of truth for roster assignment in this app.
    International Amateur and Released are parsed explicitly so they can be
    hard-excluded everywhere downstream.
    """
    s=clean(x).upper()
    # Check special populations first so mixed labels are not mistaken for an affiliate.
    for pat,team in [
        (r"\bRELEASED\b", "RELEASED"),
        (r"\bINT(?:ERNATIONAL)?[ _-]*AMAT(?:UER|EUR)\b|\bINTERNATIONAL[ _-]*AMATEUR\b", "INT AMATEUR"),
        (r"\bREHAB\b", "REHAB"),
        (r"\bDSL\b|\bDR\b", "DSL"),
        (r"\bFCL\b", "FCL"),
        (r"\bFRED(?:ERICKSBURG)?\b", "Fredericksburg"),
        (r"\bWILMINGTON\b|\bWILM\b", "Wilmington"),
        (r"\bHARRISBURG\b|\bHBG\b", "Harrisburg"),
        (r"\bROCHESTER\b|\bROC\b", "Rochester"),
        (r"\bWASHINGTON\b|\bWSH\b|\bMLB\b", "Washington"),
        (r"\bDRAFT\b", "Draft"),
    ]:
        if re.search(pat,s):
            return team
    return np.nan

def infer_day_type(x):
    """Parse the planned day tag from a STATSports session name."""
    s=clean(x)
    if re.search(r"(?i)\bhigh\b",s): return "High"
    if re.search(r"(?i)\b(?:mod|moderate)\b",s): return "Moderate"
    if re.search(r"(?i)\blow\b",s): return "Low"
    if re.search(r"(?i)\b(?:recovery|regen|regeneration)\b",s): return "Recovery"
    return np.nan


def is_lift_drill(x):
    """Identify explicit lift-only rows so they are excluded from field workload."""
    s=clean(x)
    return bool(re.fullmatch(
        r"(?i)\s*(?:lift(?:\s*\d+)?|gym|weight\s*room|weights|strength)\s*",
        s,
    ))

def three_level_day_type(x):
    """Return the exact High/Moderate/Low model tag; Recovery is grouped with Low."""
    x=clean(x)
    if x == "Recovery": return "Low"
